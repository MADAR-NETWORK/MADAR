#[repr(C)]
struct SecurityAttributes {
    n_length: u32,
    security_descriptor: *mut c_void,
    inherit_handle: i32,
}

#[link(name = "kernel32")]
extern "system" {
    fn CreateNamedPipeW(
        name: *const u16,
        open_mode: u32,
        pipe_mode: u32,
        max_instances: u32,
        out_size: u32,
        in_size: u32,
        timeout_ms: u32,
        sa: *mut SecurityAttributes,
    ) -> *mut c_void;
    fn ConnectNamedPipe(pipe: *mut c_void, overlapped: *mut c_void) -> i32;
    fn GetNamedPipeClientProcessId(pipe: *mut c_void, pid: *mut u32) -> i32;
    fn WriteFile(
        h: *mut c_void,
        buf: *const u8,
        len: u32,
        written: *mut u32,
        overlapped: *mut c_void,
    ) -> i32;
    fn FlushFileBuffers(h: *mut c_void) -> i32;
    fn CloseHandle(h: *mut c_void) -> i32;
    fn GetLastError() -> u32;
}
#[link(name = "advapi32")]
extern "system" {
    fn ConvertStringSecurityDescriptorToSecurityDescriptorW(
        sddl: *const u16,
        revision: u32,
        sd: *mut *mut c_void,
        size: *mut u32,
    ) -> i32;
}
const PIPE_ACCESS_OUTBOUND: u32 = 0x2;
const FILE_FLAG_FIRST_PIPE_INSTANCE: u32 = 0x0008_0000;
const PIPE_REJECT_REMOTE_CLIENTS: u32 = 0x8;
const ERROR_PIPE_CONNECTED: u32 = 535;

/// A pipe for a single read: a random name, one instance, no remote clients, and access for its owner only (this Windows account).
pub struct PassPipe {
    name: String,
    h: *mut c_void,
}
// SAFETY: the handle is used from one thread at a time (it is moved to the serving thread) and closed once.
unsafe impl Send for PassPipe {}

impl PassPipe {
    pub fn create() -> Result<PassPipe, &'static str> {
        let mut r = [0u8; 16];
        getrandom::getrandom(&mut r).map_err(|_| "random_failed")?;
        let name = format!(r"\\.\pipe\madar-vote-{}", super::hex(&r));
        // A protected DACL: full access for the object's owner (OW) only, instead of the default "everyone" for pipes.
        let sddl = super::wide("D:P(A;;GA;;;OW)");
        let mut sd: *mut c_void = std::ptr::null_mut();
        // SAFETY: a null-terminated UTF-16 string, and the output is a local pointer; freed with LocalFree after creation.
        if unsafe {
            ConvertStringSecurityDescriptorToSecurityDescriptorW(
                sddl.as_ptr(),
                1,
                &mut sd,
                std::ptr::null_mut(),
            )
        } == 0
        {
            return Err("pipe_failed");
        }
        let mut sa = SecurityAttributes {
            n_length: std::mem::size_of::<SecurityAttributes>() as u32,
            security_descriptor: sd,
            inherit_handle: 0,
        };
        let wname = super::wide(&name);
        // SAFETY: every pointer is valid for the whole call.
        let h = unsafe {
            CreateNamedPipeW(
                wname.as_ptr(),
                PIPE_ACCESS_OUTBOUND | FILE_FLAG_FIRST_PIPE_INSTANCE,
                PIPE_REJECT_REMOTE_CLIENTS,
                1,
                4096,
                0,
                0,
                &mut sa,
            )
        };
        // SAFETY: `sd` was allocated by the function above with LocalAlloc; the pipe copied what it needs from it.
        unsafe { LocalFree(sd) };
        if h.is_null() || h as isize == -1 {
            return Err("pipe_failed");
        }
        Ok(PassPipe { name, h })
    }

    pub fn path(&self) -> &str {
        &self.name
    }

    /// Waits for a single connection; writes the secret only if the client is the process `expected_pid`, then closes (the other side then reads the end).
    pub fn serve(self, expected_pid: u32, secret: &Secret) -> Result<(), &'static str> {
        // SAFETY: `self.h` is a valid pipe handle until drop.
        let connected = unsafe { ConnectNamedPipe(self.h, std::ptr::null_mut()) } != 0
            || unsafe { GetLastError() } == ERROR_PIPE_CONNECTED;
        if !connected {
            return Err("pipe_failed");
        }
        // The real security boundary is the pipe's DACL (owner only, `D:P(A;;GA;;;OW)`) with the random name and no remote clients.
        // The process-ID check below is an extra defence only: process IDs are reused, so it is never relied on alone.
        let mut pid = 0u32;
        // SAFETY: as above; `pid` is local.
        if unsafe { GetNamedPipeClientProcessId(self.h, &mut pid) } == 0 || pid != expected_pid {
            return Err("pipe_wrong_client");
        }
        let b = secret.as_bytes();
        let mut done = 0usize;
        while done < b.len() {
            let mut n = 0u32;
            // SAFETY: the buffer is valid for `b.len() - done` bytes.
            if unsafe {
                WriteFile(
                    self.h,
                    b[done..].as_ptr(),
                    (b.len() - done) as u32,
                    &mut n,
                    std::ptr::null_mut(),
                )
            } == 0
                || n == 0
            {
                return Err("pipe_failed");
            }
            done += n as usize;
        }
        // Waits until the other side has read every byte (or closed).
        // SAFETY: a valid handle.
        unsafe { FlushFileBuffers(self.h) };
        Ok(())
    }
}

impl Drop for PassPipe {
    fn drop(&mut self) {
        // SAFETY: closed only once.
        unsafe { CloseHandle(self.h) };
    }
}

/// Releases a pipe server nobody connected to (the child command exited before opening it): we connect ourselves, the server refuses us (another process ID) and ends.
fn poke(name: &str) {
    let _ = fs::OpenOptions::new().read(true).open(name);
}

