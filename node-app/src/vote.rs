/// The result of reading one state file (pure).
#[derive(Debug, Clone, PartialEq)]
pub enum FileRead {
    Missing,
    /// Present but could not be read now (a scanner holding it…): no decision and no write.
    Unreadable,
    /// Read, but it is not a valid JSON object.
    Corrupt,
    Ok(Value),
}

/// Which copy is used (pure, tested): the main one, then `.bak`; a read failure = skip the round; nothing valid = lost.
#[derive(Debug, Clone, PartialEq)]
pub enum Source {
    Use(Value),
    Skip,
    Lost,
}

pub fn pick_state(main: FileRead, bak: FileRead) -> Source {
    match (main, bak) {
        (FileRead::Ok(v), _) => Source::Use(v),
        (FileRead::Unreadable, _) => Source::Skip,
        (_, FileRead::Ok(v)) => Source::Use(v),
        (_, FileRead::Unreadable) => Source::Skip,
        _ => Source::Lost,
    }
}

fn read_file(f: &Path) -> FileRead {
    match fs::read_to_string(f) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => FileRead::Missing,
        Err(_) => FileRead::Unreadable,
        // The wish is the most important thing in the file: missing or not true/false = a corrupt file (`.bak` is used, then "the state was lost").
        Ok(s) => match serde_json::from_str::<Value>(&s) {
            Ok(v) if v.is_object() && v["wanted"].is_boolean() => FileRead::Ok(v),
            _ => FileRead::Corrupt,
        },
    }
}

fn local_from(v: &Value, data: &Path) -> Local {
    let s = |k: &str| v[k].as_str().map(String::from);
    let mut l = Local {
        wanted: v["wanted"].as_bool().unwrap_or(false),
        state_lost: v["wanted_unknown"].as_bool().unwrap_or(false),
        keys_expected: v["keys_expected"]
            .as_bool()
            .or_else(|| v["keys_here"].as_bool())
            .unwrap_or(false),
        rekey: v["rekey"].as_bool().unwrap_or(false),
        account_hex: s("account_hex").filter(|h| is_hex32(h)),
        pending_keys: s("pending_keys"),
        keys_checked: v["keys_checked"].as_u64(),
        keys_mismatch: v["keys_mismatch"].as_bool().unwrap_or(false),
        keys_foreign: v["keys_foreign"].as_bool().unwrap_or(false),
        sent_keys: v["last_registered_keys"]
            .as_array()
            .map(|a| {
                a.iter()
                    .filter_map(|x| x.as_str())
                    .map(keys_hex)
                    .filter(|k| k.len() == 128 && k.bytes().all(|c| c.is_ascii_hexdigit()))
                    .take(SENT_KEYS_MAX)
                    .collect()
            })
            .unwrap_or_default(),
        last_vouch: v["last_vouch"].as_u64(),
        last_apply: v["last_apply"].as_u64(),
        last_keys: v["last_keys"].as_u64(),
        last_exit: v["last_exit"].as_u64(),
        last_renew: v["last_renew"].as_u64(),
        validator: v["validator"].as_bool().unwrap_or(false),
        last_phase: s("last_phase"),
        fail_step: s("fail_step"),
        fail_count: v["fail_count"].as_u64().unwrap_or(0).min(u32::MAX as u64) as u32,
        retry_at: v["retry_at"].as_u64(),
        recreate: v["recreate"].as_bool().unwrap_or(false),
        ..Default::default()
    };
    fill_computed(&mut l, data);
    l
}

/// The fields computed from the files (not from `state.json`).
fn fill_computed(l: &mut Local, data: &Path) {
    let files = account_files(data);
    l.account = files == (true, true, true);
    l.broken = account_broken(files, l.keys_expected, l.last_phase.as_deref());
}

/// The local state: `Err` = it cannot be read now (skip the round, no write). Lost + account files present ⇒ `state_lost`.
pub fn load_local(data: &Path) -> Result<Local, &'static str> {
    match pick_state(read_file(&local_file(data)), read_file(&bak_file(data))) {
        Source::Use(v) => Ok(local_from(&v, data)),
        Source::Skip => Err("state_unreadable"),
        Source::Lost => {
            let mut l = Local {
                state_lost: any_account_file(data),
                ..Default::default()
            };
            fill_computed(&mut l, data);
            Ok(l)
        }
    }
}

/// For uninstall: the state as it is, or "lost" if it cannot be read and the account files exist (never assume the best).
pub fn gate_local(data: &Path) -> Local {
    load_local(data).unwrap_or_else(|_| Local {
        state_lost: any_account_file(data),
        ..Default::default()
    })
}

fn state_json(l: &Local) -> Value {
    json!({"wanted": l.wanted, "wanted_unknown": l.state_lost, "keys_expected": l.keys_expected, "rekey": l.rekey,
        "account_hex": l.account_hex, "pending_keys": l.pending_keys, "keys_checked": l.keys_checked, "keys_mismatch": l.keys_mismatch,
        "keys_foreign": l.keys_foreign, "last_registered_keys": l.sent_keys,
        "last_vouch": l.last_vouch, "last_apply": l.last_apply, "last_keys": l.last_keys, "last_exit": l.last_exit,
        "last_renew": l.last_renew, "validator": l.validator, "last_phase": l.last_phase, "fail_step": l.fail_step,
        "fail_count": l.fail_count, "retry_at": l.retry_at, "recreate": l.recreate})
}

/// Saves the whole state or nothing in both files (the main one, then `.bak`, an atomic write for each); a failure is returned to the caller.
pub fn save_local(data: &Path, l: &Local) -> Result<(), &'static str> {
    fs::create_dir_all(dir(data)).map_err(|_| "save_failed")?;
    let text = serde_json::to_string_pretty(&state_json(l)).unwrap_or_default();
    write_atomic(&local_file(data), text.as_bytes())?;
    write_atomic(&bak_file(data), text.as_bytes())
}

/// Read, then modify, then save (the voting thread and the page write the same file). A state that cannot be read now = never any write.
static LOCAL_LOCK: Mutex<()> = Mutex::new(());
pub fn update_local(data: &Path, f: impl FnOnce(&mut Local)) -> Result<(), &'static str> {
    let _g = LOCAL_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut l = load_local(data)?;
    f(&mut l);
    save_local(data, &l)
}

/// Creating and restoring the account never run at the same time (both check that the account files are absent, then write them).
static ACCOUNT_LOCK: Mutex<()> = Mutex::new(());

/// Does the account passphrase open here? Some(false) = definitely not (DPAPI refused, or the file format is corrupt); None = its file could not be read now
/// despite retries, or no account. Called only at start; the commands open the passphrase themselves right before running.
fn secret_check(data: &Path) -> Option<bool> {
    if !has_account(data) {
        return None;
    }
    for attempt in 1..=3u64 {
        match load_secret(data) {
            Ok(_) => return Some(true),
            Err("sealed_missing")
                if fs::metadata(sealed_file(data))
                    .is_ok_and(|m| m.is_file() && m.len() <= MAX_SEALED) =>
            {
                std::thread::sleep(Duration::from_millis(300 * attempt));
            }
            Err("sealed_missing") => return None,
            Err(_) => return Some(false),
        }
    }
    None
}

/// What is computed once at start and updated only when the app itself changes it: no DPAPI and no `node-key` read in every round.
#[derive(Debug, Clone, PartialEq)]
pub struct Cache {
    pub binding: Binding,
    /// The wish saved in the marker (it restores `wanted` if the state was lost).
    pub marker_wanted: Option<bool>,
    pub secret_ok: Option<bool>,
    /// The expected public node ID (from `data\node-key`, read once).
    pub peer: Option<String>,
    pub repicks: u32,
    /// The binding is "no decision" because the marker could not be read (or the state at start): it is read again in the round with a delay (`MARKER_RETRY`).
    pub marker_recheck: bool,
    pub marker_next: Option<Instant>,
    /// A broken account with no `.pub` and no saved address: decrypting `.enc` failed once in this run ⇒ no DPAPI in every round.
    pub enc_status_failed: bool,
}

impl Cache {
    pub fn new(
        binding: Binding,
        marker_wanted: Option<bool>,
        secret_ok: Option<bool>,
        peer: Option<String>,
    ) -> Cache {
        Cache {
            binding,
            marker_wanted,
            secret_ok,
            peer,
            repicks: 0,
            marker_recheck: false,
            marker_next: None,
            enc_status_failed: false,
        }
    }
}

/// How often a marker that could not be read is read again (seconds): first 5 minutes after start, then every 10.
pub const MARKER_RETRY_FIRST: u64 = 300;
pub const MARKER_RETRY: u64 = 600;

/// (4) The binding is "no decision" because of an unreadable marker: read it again if it is time. Returns the new binding if it became a decision (`Here`/`Moved`/
/// `NotHere`); None = not yet time, or still no decision (a new time is set). On `Valid` the sealed wish is updated too.
pub fn recheck_marker(
    data: &Path,
    cache: &mut Cache,
    keys_expected: bool,
    now: Instant,
) -> Option<Binding> {
    if cache.binding != Binding::Unverified
        || !cache.marker_recheck
        || cache.marker_next.is_some_and(|t| now < t)
    {
        return None;
    }
    let m = check_marker(data);
    let b = binding(&m, keys_expected);
    if b == Binding::Unverified {
        // Still unreadable (or the state expects keys without a marker: no re-read after that, the user decides).
        cache.marker_recheck = m == Marker::Unreadable;
        cache.marker_next = Some(now + Duration::from_secs(MARKER_RETRY));
        return None;
    }
    cache.marker_recheck = false;
    cache.marker_next = None;
    if let Marker::Valid { wanted, .. } = m {
        cache.marker_wanted = Some(wanted);
    }
    cache.binding = b;
    Some(b)
}

/// A copy of another data folder (positive evidence only): a full node, the Keystore and the marker are moved aside by renaming (no deletion),
/// then new keys are registered from here if the account is valid here (`rekey`). The same for the "Register new keys for this computer" button. Returns true if
/// the state was saved (otherwise nothing at all changes on disk: the state is read before any renaming).
fn set_keys_aside(
    p: &Paths,
    state: Option<&Arc<Mutex<State>>>,
    secret_ok: bool,
    why: &str,
) -> bool {
    if load_local(&p.data).is_err() {
        log(
            p,
            "vote: state unreadable now; nothing is set aside this time",
        );
        return false;
    }
    log(
        p,
        &format!(
            "vote: {why}; this node stays a full node and the voting keys are set aside (renamed)"
        ),
    );
    if let Some(s) = state {
        set_mode(p, s, NodeMode::Full);
    }
    let aside = set_keystore_aside(p);
    let m = marker_file(&p.data);
    if m.exists() {
        if let Err(e) = fs::rename(&m, aside_path(&m, "moved", now_unix())) {
            log(p, &format!("vote: could not set the marker aside: {e}"));
        }
    }
    match update_local(&p.data, |l| {
        l.keys_expected = false;
        l.validator = false;
        l.pending_keys = None;
        l.keys_mismatch = false;
        l.keys_foreign = false;
        // The list of sent keys was copied with the folder from another computer: it does not count as "our keys" here (no fight with the original).
        l.sent_keys.clear();
        l.rekey = secret_ok && aside;
    }) {
        Ok(()) => true,
        Err(e) => {
            log(p, &format!("vote: saving state failed: {e}"));
            false
        }
    }
}

/// The node mode when the app opens (before any chain question) and the thread's cache. Never starts with any unsafe RPC.
pub fn initial_mode(p: &Paths) -> (NodeMode, Cache) {
    let removed = clean_old_tmp(&p.data);
    if removed > 0 {
        log(
            p,
            &format!("vote: {removed} leftover temporary file(s) older than an hour were wiped"),
        );
    }
    let m = read_marker(&p.data);
    let secret_ok = secret_check(&p.data);
    let peer = super::rewards::load_key(&p.data).map(|k| super::rewards::peer_id(&k));
    let marker_wanted = match &m {
        Marker::Valid { wanted, .. } => Some(*wanted),
        _ => None,
    };
    let later = Some(Instant::now() + Duration::from_secs(MARKER_RETRY_FIRST));
    let Ok(l) = load_local(&p.data) else {
        // The state cannot be read now: a full node this time, with no decision; the round reads it again shortly (4).
        let mut c = Cache::new(Binding::Unverified, marker_wanted, secret_ok, peer);
        (c.marker_recheck, c.marker_next) = (true, later);
        return (NodeMode::Full, c);
    };
    let mut b = binding(&m, l.keys_expected);
    if b == Binding::Moved
        && set_keys_aside(
            p,
            None,
            secret_ok == Some(true),
            "the voting keys belong to another data folder",
        )
    {
        b = Binding::NotHere;
    }
    let mode =
        if b == Binding::Here && (l.validator || (l.state_lost && marker_wanted == Some(true))) {
            NodeMode::Validator
        } else {
            NodeMode::Full
        };
    let mut c = Cache::new(b, marker_wanted, secret_ok, peer);
    if b == Binding::Unverified && m == Marker::Unreadable {
        (c.marker_recheck, c.marker_next) = (true, later);
    }
    (mode, c)
}

// ---------------------------------------------------------------- Running the child commands

const IDLE_PRIORITY_CLASS: u32 = 0x0000_0040;
const MAX_OUTPUT: u64 = 256 * 1024;

#[derive(Debug)]
pub struct Failure {
    /// A code for the page.
    pub code: &'static str,
    /// Details for the log only, after the secrets are removed and the text is shortened.
    pub detail: String,
}

fn fail(code: &'static str) -> Failure {
    Failure {
        code,
        detail: String::new(),
    }
}

/// A child command's failure details for the log: the last non-empty line, without the secrets, at most 300 characters.
pub fn describe(stdout: &str, stderr: &str, secrets: &[&Secret]) -> String {
    let joined = format!("{stdout}\n{stderr}");
    let last = joined
        .lines()
        .rev()
        .map(str::trim)
        .find(|l| !l.is_empty())
        .unwrap_or("");
    redact(last, secrets).chars().take(300).collect()
}

/// Runs `madar-node.exe` (alone, with explicit arguments) and waits for it to end. The secrets, if any, are handed over through the pipes only.
/// The process is inside the app's job object (it dies with the app), and it is ended at once if `cancel()` becomes true (the node stopped or was paused).
fn run(
    p: &Paths,
    args: &[String],
    pipes: Vec<(PassPipe, &Secret)>,
    priority: u32,
    timeout: Duration,
    cancel: &(dyn Fn() -> bool + Sync),
) -> Result<String, Failure> {
    let secrets: Vec<&Secret> = pipes.iter().map(|(_, s)| *s).collect();
    let mut child = Command::new(&p.node_exe)
        .args(args)
        .current_dir(&p.root)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .creation_flags(CREATE_NO_WINDOW | priority)
        .spawn()
        .map_err(|e| Failure {
            code: "spawn_failed",
            detail: e.to_string(),
        })?;
    if !super::tie_to_app(&child) {
        log(
            p,
            "vote: could not tie the join command to the app (job object)",
        );
    }
    if priority == IDLE_PRIORITY_CLASS {
        limit_cores(p, child.id());
    }
    let pid = child.id();
    let names: Vec<String> = pipes.iter().map(|(x, _)| x.path().to_string()).collect();
    let (mut so, mut se) = (child.stdout.take(), child.stderr.take());
    let (status, cancelled, out, err, served) = std::thread::scope(|sc| {
        let ho = sc.spawn(move || {
            let mut s = Vec::new();
            if let Some(o) = so.as_mut() {
                let _ = o.take(MAX_OUTPUT).read_to_end(&mut s);
            }
            String::from_utf8_lossy(&s).to_string()
        });
        let he = sc.spawn(move || {
            let mut s = Vec::new();
            if let Some(o) = se.as_mut() {
                let _ = o.take(MAX_OUTPUT).read_to_end(&mut s);
            }
            String::from_utf8_lossy(&s).to_string()
        });
        let hs: Vec<_> = pipes
            .into_iter()
            .map(|(pp, sec)| sc.spawn(move || pp.serve(pid, sec)))
            .collect();
        let deadline = Instant::now() + timeout;
        let mut cancelled = false;
        let mut checked = Instant::now();
        let status = loop {
            match child.try_wait() {
                Ok(Some(s)) => break Some(s),
                Ok(None) if Instant::now() < deadline && !cancelled => {
                    std::thread::sleep(Duration::from_millis(300));
                    if checked.elapsed() >= Duration::from_secs(3) {
                        checked = Instant::now();
                        cancelled = cancel();
                    }
                }
                _ => {
                    let _ = child.kill();
                    let _ = child.wait();
                    break None;
                }
            }
        };
        let served: Vec<Result<(), &'static str>> = hs
            .into_iter()
            .zip(names.iter())
            .map(|(h, n)| {
                if !h.is_finished() {
                    poke(n);
                }
                h.join().unwrap_or(Err("pipe_failed"))
            })
            .collect();
        (
            status,
            cancelled,
            ho.join().unwrap_or_default(),
            he.join().unwrap_or_default(),
            served,
        )
    });
    let detail = describe(&out, &err, &secrets);
    match status {
        None if cancelled => Err(Failure {
            code: "cancelled",
            detail,
        }),
        None => Err(Failure {
            code: "timeout",
            detail,
        }),
        Some(s) if s.success() => Ok(redact(&out, &secrets)),
        Some(_) if served.contains(&Err("pipe_wrong_client")) => Err(Failure {
            code: "pipe_wrong_client",
            detail,
        }),
        Some(_) => Err(Failure {
            code: "command_failed",
            detail,
        }),
    }
}

