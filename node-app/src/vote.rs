/// The uninstall decision.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Gate {
    Allow,
    /// Refused (voting is wanted, or the chain says it is a candidate/member/exiting, or the wish and the phase are unknown and the account exists).
    Blocked,
    /// The chain cannot be reached now and the last saved phase is "started": a forced uninstall is offered with a clear warning.
    ForceOffer,
}

/// Uninstall (pure, tested): `fresh` = (the phase, in the current authority set) from the chain now (None = unreachable),
/// `force` = the user confirmed the warning. Removing the app during membership leaves an absent member that counts against finality, and deleting the data destroys
/// the account before the exit completes. A current authority (`active`) blocks uninstalling whatever the phase (the exit completes after the session ends).
pub fn uninstall_gate(l: &Local, fresh: Option<(&str, bool)>, force: bool) -> Gate {
    if l.wanted && !l.state_lost {
        return Gate::Blocked;
    }
    match fresh {
        Some((ph, active)) if active || started(Some(ph)) => Gate::Blocked,
        Some(_) => Gate::Allow,
        None if l.state_lost => Gate::Blocked,
        None if l.validator || started(l.last_phase.as_deref()) => {
            if force {
                Gate::Allow
            } else {
                Gate::ForceOffer
            }
        }
        None => Gate::Allow,
    }
}

/// A new RPC port after our port was found owned by another process: the first free port after the current one within 64, equal to no port the app
/// knows (pure, tested; `free` is injected).
pub fn next_rpc_port(current: u16, avoid: &[u16], free: impl Fn(u16) -> bool) -> Option<u16> {
    (1..=64u16)
        .filter_map(|i| current.checked_add(i))
        .find(|p| !avoid.contains(p) && free(*p))
}

/// The maximum number of port re-picks in one run of the app (after it the "another program on the port" phase stays).
pub const MAX_REPICKS: u32 = 3;

