#[link(name = "iphlpapi")]
extern "system" {
    fn GetExtendedTcpTable(
        table: *mut c_void,
        size: *mut u32,
        order: i32,
        af: u32,
        class: u32,
        reserved: u32,
    ) -> u32;
}
const AF_INET: u32 = 2;
const TCP_TABLE_OWNER_PID_LISTENER: u32 = 3;
const ERROR_INSUFFICIENT_BUFFER: u32 = 122;

/// Every listening IPv4 socket: (local address, port, owning process ID). Read-only from the Windows table.
pub fn tcp_listeners() -> Vec<([u8; 4], u16, u32)> {
    let mut size: u32 = 0;
    // SAFETY: the first call only asks for the size (NULL buffer).
    unsafe {
        GetExtendedTcpTable(
            std::ptr::null_mut(),
            &mut size,
            0,
            AF_INET,
            TCP_TABLE_OWNER_PID_LISTENER,
            0,
        )
    };
    for _ in 0..4 {
        // A buffer of u32 (MIB_TCPTABLE_OWNER_PID alignment) with a margin for a table that grows between the two calls.
        let mut buf = vec![0u32; size as usize / 4 + 256];
        let mut got = (buf.len() * 4) as u32;
        // SAFETY: `buf` holds `got` bytes, and the function never writes more.
        let r = unsafe {
            GetExtendedTcpTable(
                buf.as_mut_ptr().cast(),
                &mut got,
                0,
                AF_INET,
                TCP_TABLE_OWNER_PID_LISTENER,
                0,
            )
        };
        if r == ERROR_INSUFFICIENT_BUFFER {
            size = got;
            continue;
        }
        if r != 0 {
            return Vec::new();
        }
        // MIB_TCPTABLE_OWNER_PID: dwNumEntries, then rows of 6 u32 values: state, localAddr, localPort, remoteAddr, remotePort, pid.
        let n = buf[0] as usize;
        return (0..n)
            .filter_map(|i| buf.get(1 + i * 6..1 + i * 6 + 6))
            .map(|r| {
                (
                    r[1].to_le_bytes(),
                    (((r[2] & 0xff) << 8) | ((r[2] >> 8) & 0xff)) as u16,
                    r[5],
                )
            })
            .collect();
    }
    Vec::new()
}

/// The port is listened on (on 127.0.0.1 or all addresses) only by the node program the app started (pure, tested).
pub fn listener_owned_by(rows: &[([u8; 4], u16, u32)], port: u16, pid: u32) -> bool {
    let mut on_port = rows
        .iter()
        .filter(|r| r.1 == port && (r.0 == [127, 0, 0, 1] || r.0 == [0, 0, 0, 0]))
        .peekable();
    on_port.peek().is_some() && on_port.all(|r| r.2 == pid)
}

/// The node ID announced by the RPC matches the ID derived from the `data\node-key` key (pure, tested).
pub fn peer_matches(reported: Option<&str>, expected: Option<&str>) -> bool {
    matches!((reported, expected), (Some(a), Some(b)) if !a.is_empty() && a == b)
}

/// Before a `join` command over RPC: the network node ID is ours (saved at start); and before sending commands also: the port belongs to the node process
/// we started (the TCP table is read here only). Otherwise no command (another process that took the port could fake the state).
fn verify_rpc(
    p: &Paths,
    state: &Arc<Mutex<State>>,
    port: u16,
    peer: Option<&str>,
    full: bool,
) -> Result<(), Failure> {
    let pid = {
        let mut st = state.lock().unwrap();
        if !super::node_alive(&mut st) {
            return Err(fail("rpc_not_ours"));
        }
        st.child
            .as_ref()
            .map(std::process::Child::id)
            .ok_or_else(|| fail("rpc_not_ours"))?
    };
    if full && !listener_owned_by(&tcp_listeners(), port, pid) {
        log(
            p,
            &format!("vote: RPC port {port} is not held by our node (pid {pid}); refusing"),
        );
        return Err(fail("rpc_not_ours"));
    }
    let reported =
        rpc(port, "system_localPeerId", json!([])).and_then(|v| v.as_str().map(String::from));
    if !peer_matches(reported.as_deref(), peer) {
        log(
            p,
            "vote: the RPC answers with another node identity; refusing",
        );
        return Err(fail("rpc_not_ours"));
    }
    Ok(())
}

/// Runs a `join` command: `op` is the operator account passphrase (if it is not given and the command needs it, it is opened here, right before the command), and `second` is the
/// backup password. `state` = None for a command that does not talk to the RPC (or while the node is stopped on purpose).
fn run_join(
    p: &Paths,
    state: Option<&Arc<Mutex<State>>>,
    peer: Option<&str>,
    cmd: &Join,
    rpc_port: u16,
    op: Option<&Secret>,
    second: Option<&Secret>,
) -> Result<String, Failure> {
    let enc = enc_file(&p.data);
    let priority = if matches!(cmd, Join::Apply | Join::AutoRenew) {
        IDLE_PRIORITY_CLASS
    } else {
        BELOW_NORMAL_PRIORITY_CLASS
    };
    let timeout = Duration::from_secs(timeout_secs(cmd));
    let never = || false;
    let node_gone = || {
        state.is_some_and(|s| {
            let mut st = s.lock().unwrap();
            st.stopping || st.paused.is_some() || !super::node_alive(&mut st)
        })
    };
    let cancel: &(dyn Fn() -> bool + Sync) = if cmd.uses_rpc() { &node_gone } else { &never };
    if cmd.uses_rpc() {
        let s = state.ok_or_else(|| fail("rpc_not_ours"))?;
        verify_rpc(p, s, rpc_port, peer, cmd.sends())?;
    }
    let owned;
    let op = match op {
        Some(s) => Some(s),
        None if cmd.needs_secret() => {
            owned = load_secret(&p.data).map_err(fail)?;
            Some(&owned)
        }
        None => None,
    };
    let mut pipes = Vec::new();
    let (mut pass_path, mut second_path) = (None, None);
    if let Some(s) = op {
        let pp = PassPipe::create().map_err(fail)?;
        pass_path = Some(pp.path().to_string());
        pipes.push((pp, s));
    }
    if let Some(s) = second {
        let pp = PassPipe::create().map_err(fail)?;
        second_path = Some(pp.path().to_string());
        pipes.push((pp, s));
    }
    let ctx = ArgCtx {
        enc: &enc,
        base: &p.base,
        spec: &p.spec,
        rpc_port,
    };
    let args = join_args(cmd, &ctx, pass_path.as_deref(), second_path.as_deref());
    run(p, &args, pipes, priority, timeout, cancel)
}

