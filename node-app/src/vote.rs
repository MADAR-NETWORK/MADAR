/// The "Enable/Stop voting" buttons (and confirming the wish after the state was lost): they only save the wish; the thread carries it out. The wish is also saved in
/// the sealed marker if it is valid. Returns the save error if saving failed.
pub fn set_wanted(p: &Paths, state: &Arc<Mutex<State>>, on: bool) -> Result<(), &'static str> {
    update_local(&p.data, |l| {
        l.wanted = on;
        l.state_lost = false;
    })?;
    if let Marker::Valid { id, wanted } = check_marker(&p.data) {
        if wanted != on {
            if let Err(e) = make_marker(&p.data, on, Some(&id)) {
                log(
                    p,
                    &format!("vote: the sealed marker could not record the choice: {e}"),
                );
            }
        }
    }
    log(
        p,
        &format!("vote: {} by user", if on { "enable" } else { "stop" }),
    );
    let mut st = state.lock().unwrap();
    st.vote["wanted"] = json!(on);
    st.vote_kick = true;
    Ok(())
}

/// The "Recreate the operator account" button: the request is accepted only for a broken account here; the thread checks the chain (not started) before moving anything aside.
pub fn request_recreate(p: &Paths, state: &Arc<Mutex<State>>) -> Result<(), &'static str> {
    // `can_recreate` is computed by the thread from a broken account here and the chain state; the thread checks again before moving anything aside.
    let can = state.lock().unwrap().vote["can_recreate"]
        .as_bool()
        .unwrap_or(false);
    if !can || !load_local(&p.data)?.wanted {
        return Err("not_allowed");
    }
    update_local(&p.data, |l| l.recreate = true)?;
    log(p, "vote: re-create operator account requested by user");
    state.lock().unwrap().vote_kick = true;
    Ok(())
}

/// The "Register new keys for this computer" button: only in the "could not verify" phase (the thread moves the keys aside by renaming, then registers
/// new ones) or "another computer's keys on the network" (this computer takes over the account with new keys).
pub fn request_rekey(state: &Arc<Mutex<State>>) -> Result<(), &'static str> {
    let mut st = state.lock().unwrap();
    if st.vote["stage"] != "cannot_verify" && st.vote["stage"] != "keys_other_device" {
        return Err("not_allowed");
    }
    st.vote_rekey = true;
    st.vote_kick = true;
    Ok(())
}

/// "Save an encrypted backup": returns the backup file's text (JSON encrypted with the user's password) for the page to save. The passphrase is opened here right before
/// the command, and both passwords pass through one-time pipes. No backup file is left in the data folder.
pub fn backup(p: &Paths, password: &Secret) -> Result<String, &'static str> {
    if !has_account(&p.data) {
        return Err("no_operator_account");
    }
    let mut r = [0u8; 8];
    getrandom::getrandom(&mut r).map_err(|_| "random_failed")?;
    let out = dir(&p.data).join(format!("export-{}.tmp", super::hex(&r)));
    let res = run_join(
        p,
        None,
        None,
        &Join::Export(out.clone()),
        0,
        None,
        Some(password),
    );
    let text = fs::read_to_string(&out).ok();
    let _ = fs::remove_file(&out);
    match (res, text) {
        (Ok(_), Some(t)) if t.contains("madar-operator-backup-v1") => {
            log(
                p,
                "vote: an encrypted backup of the operator account was made by the user",
            );
            Ok(t)
        }
        (Err(f), _) => {
            log(p, &format!("vote: backup failed: {} {}", f.code, f.detail));
            Err(if f.code == "unseal_failed" {
                "unseal_failed"
            } else {
                "backup_failed"
            })
        }
        _ => Err("backup_failed"),
    }
}

/// "Restore the account": on a computer without an operator account, from the backup file's text and its password. A new passphrase is sealed for this computer, then
/// `join import`. After that: new session keys for this computer (`rekey`), and the wish is "enabled".
pub fn restore(
    p: &Paths,
    state: &Arc<Mutex<State>>,
    text: &str,
    password: &Secret,
) -> Result<(), &'static str> {
    if text.len() > 64 * 1024 || !text.contains("madar-operator-backup-v1") {
        return Err("not_a_backup");
    }
    let _g = ACCOUNT_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    if any_account_file(&p.data) {
        return Err("account_exists");
    }
    fs::create_dir_all(dir(&p.data)).map_err(|_| "save_failed")?;
    let mut r = [0u8; 8];
    getrandom::getrandom(&mut r).map_err(|_| "random_failed")?;
    let input = dir(&p.data).join(format!("import-{}.tmp", super::hex(&r)));
    write_atomic(&input, text.as_bytes())?;
    let secret = Secret::random()?;
    let res = write_new_sealed(&p.data, &secret).and_then(|_| {
        run_join(
            p,
            None,
            None,
            &Join::Import(input.clone()),
            0,
            Some(&secret),
            Some(password),
        )
    });
    let _ = fs::remove_file(&input);
    if let Err(f) = res {
        if !enc_file(&p.data).exists() && !pub_file(&p.data).exists() {
            let _ = fs::remove_file(sealed_file(&p.data));
        }
        log(p, &format!("vote: restore failed: {} {}", f.code, f.detail));
        return Err(if f.code == "command_failed" {
            "restore_failed"
        } else {
            f.code
        });
    }
    if !has_account(&p.data) {
        return Err("restore_failed");
    }
    let h = account_id_hex(&p.data);
    update_local(&p.data, |l| {
        l.wanted = true;
        l.state_lost = false;
        l.rekey = true;
        l.account_hex = h.clone();
        l.keys_expected = false;
        l.pending_keys = None;
        l.keys_foreign = false;
        l.sent_keys.clear();
        l.fail_step = None;
        l.fail_count = 0;
        l.retry_at = None;
    })?;
    log(p, "vote: the operator account was restored from an encrypted backup; new voting keys will be registered for this computer");
    let mut st = state.lock().unwrap();
    st.vote["address"] = json!(address(&p.data));
    st.vote_kick = true;
    Ok(())
}

/// For uninstall: (the phase, in the current authority set) from the chain now, if the node is ready and the RPC is our node. Saves the phase in
/// `last_phase`.
pub fn fresh_phase(p: &Paths, state: &Arc<Mutex<State>>) -> Option<(String, bool)> {
    let l = load_local(&p.data).ok()?;
    let port = node_ready(state)?;
    let peer = super::rewards::load_key(&p.data).map(|k| super::rewards::peer_id(&k));
    let mut cache = Cache::new(Binding::NotHere, None, None, peer);
    let c = chain_status(p, state, &mut cache, &l, port).0.ok()?;
    let phase = phase_name(c.phase).to_string();
    let _ = update_local(&p.data, |x| x.last_phase = Some(phase.clone()));
    Some((phase, c.active))
}

