#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Join {
    NewAccount,
    /// The account status from `operator.pub` (or by decrypting `.enc` if the passphrase is passed and `.pub` is missing).
    Status,
    /// The status of an account by its public ID (a broken account whose address we know from the state).
    StatusOf(String),
    Vouch,
    Apply,
    /// `register-keys --keys` with the public keys from `gen-keys`.
    RegisterKeys(String),
    Exit,
    AutoRenew,
    /// `gen-keys` while the node is stopped.
    GenKeys,
    /// `export --out <file>`.
    Export(PathBuf),
    /// `import --in <file>`.
    Import(PathBuf),
}

impl Join {
    /// Needs the operator account passphrase (opened right before the command).
    pub fn needs_secret(&self) -> bool {
        !matches!(
            self,
            Join::Status | Join::StatusOf(_) | Join::GenKeys | Join::Import(_)
        )
    }
    /// Sends a transaction or touches the keys over RPC: a full RPC check (port table + node ID) before it.
    pub fn sends(&self) -> bool {
        matches!(
            self,
            Join::Vouch | Join::Apply | Join::RegisterKeys(_) | Join::Exit | Join::AutoRenew
        )
    }
    /// Talks to the node's RPC at all.
    pub fn uses_rpc(&self) -> bool {
        self.sends() || matches!(self, Join::Status | Join::StatusOf(_))
    }
}

/// The paths the arguments need.
pub struct ArgCtx<'a> {
    pub enc: &'a Path,
    pub base: &'a Path,
    pub spec: &'a Path,
    pub rpc_port: u16,
}

/// `madar-node join …` arguments: RPC always on 127.0.0.1 (the app's own node), and the secrets are **file paths only** (the pipes):
/// `pass` for the operator account passphrase, and `second` for the backup password.
pub fn join_args(cmd: &Join, c: &ArgCtx, pass: Option<&str>, second: Option<&str>) -> Vec<String> {
    let s = |x: &str| x.to_string();
    let rpc = format!("127.0.0.1:{}", c.rpc_port);
    let enc = c.enc.display().to_string();
    let pass_args = || -> Vec<String> {
        pass.map(|p| vec![s("--passphrase-file"), s(p)])
            .unwrap_or_default()
    };
    let tx = |name: &str| -> Vec<String> {
        let mut v = vec![
            s("join"),
            s(name),
            s("--rpc"),
            rpc.clone(),
            s("--account-file"),
            enc.clone(),
        ];
        v.extend(pass_args());
        v.push(s("--yes"));
        v
    };
    let node = || {
        vec![
            s("--base-path"),
            c.base.display().to_string(),
            s("--chain"),
            c.spec.display().to_string(),
        ]
    };
    match cmd {
        Join::NewAccount => {
            let mut v = vec![s("join"), s("new-account"), s("--out"), enc.clone()];
            v.extend(pass_args());
            v
        }
        Join::Status => {
            let mut v = vec![
                s("join"),
                s("status"),
                s("--rpc"),
                rpc.clone(),
                s("--account-file"),
                enc.clone(),
                s("--json"),
            ];
            v.extend(pass_args());
            v
        }
        Join::StatusOf(addr) => vec![
            s("join"),
            s("status"),
            s("--rpc"),
            rpc.clone(),
            s("--address"),
            format!("0x{addr}"),
            s("--json"),
        ],
        Join::Vouch => tx("vouch"),
        Join::Apply => tx("apply"),
        Join::RegisterKeys(keys) => {
            let mut v = tx("register-keys");
            v.extend([s("--keys"), keys.clone()]);
            v.extend(node());
            v
        }
        Join::Exit => tx("exit"),
        // As in the operator auto-renew script: renews only when about two days (24 sessions) are left, and re-applies after losing the draw.
        Join::AutoRenew => {
            let mut v = vec![
                s("join"),
                s("auto-renew"),
                s("--rpc"),
                rpc.clone(),
                s("--account-file"),
                enc.clone(),
            ];
            v.extend(pass_args());
            v.extend([
                s("--renew-within"),
                RENEW_WITHIN.to_string(),
                s("--reapply"),
            ]);
            v
        }
        Join::GenKeys => {
            let mut v = vec![s("join"), s("gen-keys")];
            v.extend(node());
            v.push(s("--json"));
            v
        }
        Join::Export(out) => {
            let mut v = vec![s("join"), s("export"), s("--account-file"), enc.clone()];
            v.extend(pass_args());
            if let Some(b) = second {
                v.extend([s("--backup-pass-file"), s(b)]);
            }
            v.extend([s("--out"), out.display().to_string()]);
            v
        }
        Join::Import(input) => {
            let mut v = vec![
                s("join"),
                s("import"),
                s("--in"),
                input.display().to_string(),
            ];
            if let Some(b) = second {
                v.extend([s("--backup-pass-file"), s(b)]);
            }
            v.extend([s("--out"), enc.clone()]);
            v.extend(pass_args());
            v
        }
    }
}

/// The public keys from the `gen-keys --json` output (pure, tested): the SessionKeys encoding (64 bytes) + the two expected Keystore names.
pub fn parse_gen_keys(out: &str) -> Result<(String, [String; 2]), &'static str> {
    let v: Value = serde_json::from_str(out.trim()).map_err(|_| "keys_unreadable")?;
    let keys = v["keys"]
        .as_str()
        .ok_or("keys_unreadable")?
        .trim_start_matches("0x")
        .to_lowercase();
    let (babe, gran) = (
        v["babe"]
            .as_str()
            .unwrap_or("")
            .trim_start_matches("0x")
            .to_lowercase(),
        v["grandpa"]
            .as_str()
            .unwrap_or("")
            .trim_start_matches("0x")
            .to_lowercase(),
    );
    if keys.len() != 128
        || !keys.bytes().all(|c| c.is_ascii_hexdigit())
        || keys[..64] != babe
        || keys[64..] != gran
    {
        return Err("keys_unreadable");
    }
    Ok((
        format!("0x{keys}"),
        [format!("62616265{babe}"), format!("6772616e{gran}")],
    ))
}

