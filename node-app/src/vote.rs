/// A chain phase in which the account has started something (candidacy/membership/exit).
pub fn started(phase: Option<&str>) -> bool {
    matches!(
        phase,
        Some("candidate" | "member" | "member_in_grace" | "exiting")
    )
}

/// The account is broken (pure, tested): incomplete leftovers of its files, or no files at all while the state says keys were registered from
/// here or that the account started on the chain (a used account disappeared: no other one is created silently).
pub fn account_broken(
    files: (bool, bool, bool),
    keys_expected: bool,
    last_phase: Option<&str>,
) -> bool {
    match files {
        (true, true, true) => false,
        (false, false, false) => keys_expected || started(last_phase),
        _ => true,
    }
}

/// The account's public ID (hex, 32 bytes) from `operator.pub`.
fn account_id_hex(data: &Path) -> Option<String> {
    let text = fs::read_to_string(pub_file(data)).ok()?;
    let h = text
        .lines()
        .find_map(|l| l.strip_prefix("account_id_hex="))?
        .trim()
        .trim_start_matches("0x")
        .to_lowercase();
    is_hex32(&h).then_some(h)
}

fn is_hex32(h: &str) -> bool {
    h.len() == 64 && h.bytes().all(|c| c.is_ascii_hexdigit())
}

/// The public address (SS58) from `operator.pub`: not a secret, shown with a copy button.
pub fn address(data: &Path) -> Option<String> {
    let text = fs::read_to_string(pub_file(data)).ok()?;
    text.lines()
        .find_map(|l| l.strip_prefix("ss58="))
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
}

/// Zeros over the file, then delete it (wiping guarantees nothing on an SSD or in shadow copies). Returns true if it was deleted.
fn wipe_file(f: &Path) -> bool {
    if let Ok(len) = fs::metadata(f).map(|m| m.len()) {
        if let Ok(mut h) = fs::OpenOptions::new().write(true).open(f) {
            let _ = h.write_all(&vec![0u8; len as usize]);
            let _ = h.sync_all();
        }
    }
    fs::remove_file(f).is_ok()
}

/// Every file in a folder (no subfolders) is wiped, then the folder is deleted. Returns true if nothing is left.
fn wipe_dir(d: &Path) -> bool {
    let files: Vec<PathBuf> = fs::read_dir(d)
        .map(|rd| {
            rd.flatten()
                .map(|e| e.path())
                .filter(|f| f.is_file())
                .collect()
        })
        .unwrap_or_default();
    let all = files.iter().fold(true, |ok, f| wipe_file(f) && ok);
    all && fs::remove_dir(d).is_ok()
}

/// Full deletion ("delete your data" on uninstall, on the user's explicit request): zeros over every file in `data\vote`, then delete.
/// (The sealed files can only be opened by this Windows account anyway.) Only called while the app is stopped and its lock is held (`cmd_uninstall`).
/// This module deletes in three places only: here, old temporary files (`clean_old_tmp`), and a Keystore moved aside once it is confirmed that
/// the chain does not name its keys (`wipe_stale_aside`); everything else is renaming.
pub fn destroy(data: &Path) {
    wipe_dir(&dir(data));
}

/// Older than this (seconds), a temporary file counts as the leftover of an interrupted command (backup, restore or state write).
pub const TMP_MAX_AGE: u64 = 3600;

/// At start: every `data\vote\*.tmp` older than an hour is wiped, then deleted (it may hold an encrypted backup's text). Returns how many were deleted.
pub fn clean_old_tmp(data: &Path) -> usize {
    let old = |m: &fs::Metadata| {
        m.modified()
            .ok()
            .and_then(|t| t.elapsed().ok())
            .is_some_and(|age| age.as_secs() >= TMP_MAX_AGE)
    };
    let files: Vec<PathBuf> = fs::read_dir(dir(data))
        .map(|rd| {
            rd.flatten()
                .filter(|e| {
                    e.path().extension().is_some_and(|x| x == "tmp")
                        && e.metadata().is_ok_and(|m| m.is_file() && old(&m))
                })
                .map(|e| e.path())
                .collect()
        })
        .unwrap_or_default();
    files.iter().filter(|f| wipe_file(f)).count()
}

/// The "moved aside" name for a file or folder (never deleted).
fn aside_path(f: &Path, tag: &str, stamp: u64) -> PathBuf {
    let name = f.file_name().and_then(|n| n.to_str()).unwrap_or("file");
    f.with_file_name(format!("{name}.{tag}-{stamp}"))
}

// ---------------------------------------------------------------- The secret in memory

/// A secret in memory (the account passphrase or the backup password). Deliberately no `Debug`/`Display`/`Clone`, and wiped on drop.
pub struct Secret(Vec<u8>);

impl Secret {
    /// 32 random bytes from the operating system, written as hex (64 characters; `join` requires at least 12).
    pub fn random() -> Result<Secret, &'static str> {
        let mut raw = [0u8; 32];
        getrandom::getrandom(&mut raw).map_err(|_| "random_failed")?;
        let mut out = Vec::with_capacity(64);
        for b in raw {
            for nib in [b >> 4, b & 0xf] {
                out.push(b"0123456789abcdef"[nib as usize]);
            }
        }
        wipe(&mut raw);
        Ok(Secret(out))
    }
    /// A password typed by the user (the backup): 12–256 characters, no control characters (the pipe is read as a single line).
    pub fn from_user(text: &str) -> Result<Secret, &'static str> {
        let n = text.chars().count();
        if n < BACKUP_PASS_MIN {
            return Err("password_short");
        }
        if n > 256 || text.chars().any(char::is_control) {
            return Err("password_bad");
        }
        Ok(Secret(text.as_bytes().to_vec()))
    }
    fn as_bytes(&self) -> &[u8] {
        &self.0
    }
    fn as_str(&self) -> &str {
        std::str::from_utf8(&self.0).unwrap_or("")
    }
}

impl Drop for Secret {
    fn drop(&mut self) {
        wipe(&mut self.0);
    }
}

/// The minimum length of the backup password (same as `join`).
pub const BACKUP_PASS_MIN: usize = 12;

/// Writes zeros the compiler cannot remove.
pub fn wipe(buf: &mut [u8]) {
    for b in buf.iter_mut() {
        // SAFETY: `b` is a valid writable reference to a single byte.
        unsafe { std::ptr::write_volatile(b, 0) };
    }
    std::sync::atomic::compiler_fence(std::sync::atomic::Ordering::SeqCst);
}

/// Removes any appearance of the secrets from a text (a child command's output, before any log or message).
pub fn redact(text: &str, secrets: &[&Secret]) -> String {
    let mut out = text.to_string();
    for s in secrets.iter().map(|s| s.as_str()).filter(|s| !s.is_empty()) {
        out = out.replace(s, "[hidden]");
    }
    out
}

// ---------------------------------------------------------------- Sealing with DPAPI (crypt32, no PowerShell)

pub const FORMAT: &str = "madar-dpapi-v1";
pub const PURPOSE: &str = "operator-passphrase";
const ENTROPY: &[u8] = b"MADAR-operator-passphrase-v1";
const MAX_SEALED: u64 = 64 * 1024;

#[repr(C)]
struct DataBlob {
    cb_data: u32,
    pb_data: *mut u8,
}
const CRYPTPROTECT_UI_FORBIDDEN: u32 = 0x1;
const CRYPTPROTECT_LOCAL_MACHINE: u32 = 0x4;

#[link(name = "crypt32")]
extern "system" {
    fn CryptProtectData(
        data_in: *const DataBlob,
        description: *const u16,
        entropy: *const DataBlob,
        reserved: *mut c_void,
        prompt: *mut c_void,
        flags: u32,
        data_out: *mut DataBlob,
    ) -> i32;
    fn CryptUnprotectData(
        data_in: *const DataBlob,
        description: *mut *mut u16,
        entropy: *const DataBlob,
        reserved: *mut c_void,
        prompt: *mut c_void,
        flags: u32,
        data_out: *mut DataBlob,
    ) -> i32;
}

#[link(name = "kernel32")]
extern "system" {
    fn LocalFree(mem: *mut c_void) -> *mut c_void;
}

fn blob(b: &[u8]) -> DataBlob {
    // DPAPI does not write to its inputs; *mut only because the C signature is not const.
    DataBlob {
        cb_data: b.len() as u32,
        pb_data: b.as_ptr() as *mut u8,
    }
}

/// SAFETY: `out` was returned by a successful DPAPI call (LocalAlloc memory we own). It is copied, wiped if it is a secret, then freed.
unsafe fn take(out: DataBlob, secret: bool) -> Vec<u8> {
    let s = std::slice::from_raw_parts_mut(out.pb_data, out.cb_data as usize);
    let mut v = Vec::with_capacity(s.len());
    v.extend_from_slice(s);
    if secret {
        wipe(s);
    }
    LocalFree(out.pb_data.cast());
    v
}

/// A raw DPAPI seal: CurrentUser (default) or LocalMachine.
fn protect(bytes: &[u8], entropy: &[u8], local_machine: bool) -> Result<Vec<u8>, &'static str> {
    let (input, ent) = (blob(bytes), blob(entropy));
    let mut out = DataBlob {
        cb_data: 0,
        pb_data: std::ptr::null_mut(),
    };
    let flags = CRYPTPROTECT_UI_FORBIDDEN
        | if local_machine {
            CRYPTPROTECT_LOCAL_MACHINE
        } else {
            0
        };
    // SAFETY: every pointer is valid for the whole call; the optional ones are NULL as the documentation allows.
    let ok = unsafe {
        CryptProtectData(
            &input,
            std::ptr::null(),
            &ent,
            std::ptr::null_mut(),
            std::ptr::null_mut(),
            flags,
            &mut out,
        )
    };
    if ok == 0 || out.pb_data.is_null() {
        return Err("seal_failed");
    }
    // SAFETY: the call above succeeded; the output is sealed, not a plain secret.
    Ok(unsafe { take(out, false) })
}

fn unprotect(sealed: &[u8], entropy: &[u8]) -> Result<Secret, &'static str> {
    let (input, ent) = (blob(sealed), blob(entropy));
    let mut out = DataBlob {
        cb_data: 0,
        pb_data: std::ptr::null_mut(),
    };
    // SAFETY: as in `protect`; the data description is not needed (NULL).
    let ok = unsafe {
        CryptUnprotectData(
            &input,
            std::ptr::null_mut(),
            &ent,
            std::ptr::null_mut(),
            std::ptr::null_mut(),
            CRYPTPROTECT_UI_FORBIDDEN,
            &mut out,
        )
    };
    if ok == 0 || out.pb_data.is_null() {
        return Err("unseal_failed");
    }
    // SAFETY: the call above succeeded; the output is a plain secret, so it is wiped before being freed.
    Ok(Secret(unsafe { take(out, true) }))
}

fn unhex(data: &str) -> Option<Vec<u8>> {
    if !data.len().is_multiple_of(2) {
        return None;
    }
    (0..data.len())
        .step_by(2)
        .map(|i| {
            data.get(i..i + 2)
                .and_then(|b| u8::from_str_radix(b, 16).ok())
        })
        .collect()
}

/// Seals the secret and returns the sealed file's content (JSON, CurrentUser scope).
pub fn seal(secret: &Secret) -> Result<Vec<u8>, &'static str> {
    let sealed = protect(secret.as_bytes(), ENTROPY, false)?;
    let f = json!({"format": FORMAT, "purpose": PURPOSE, "scope": "CurrentUser", "data": super::hex(&sealed)});
    serde_json::to_vec_pretty(&f).map_err(|_| "seal_failed")
}

/// Opens a sealed file's content. Errors are fixed codes that never carry any part of the content.
pub fn unseal(file: &[u8]) -> Result<Secret, &'static str> {
    let v: Value = serde_json::from_slice(file).map_err(|_| "sealed_bad_format")?;
    if v["format"] != FORMAT || v["purpose"] != PURPOSE || v["scope"] != "CurrentUser" {
        return Err("sealed_bad_format");
    }
    let sealed =
        unhex(v["data"].as_str().ok_or("sealed_bad_format")?).ok_or("sealed_bad_format")?;
    unprotect(&sealed, ENTROPY)
}

fn load_secret(data: &Path) -> Result<Secret, &'static str> {
    let f = sealed_file(data);
    if fs::metadata(&f)
        .map(|m| !m.is_file() || m.len() > MAX_SEALED)
        .unwrap_or(true)
    {
        return Err("sealed_missing");
    }
    let bytes = fs::read(&f).map_err(|_| "sealed_missing")?;
    unseal(&bytes)
}

// ---------------------------------------------------------------- "The keys are here": a marker sealed twice

const MARKER_PURPOSE: &str = "keys-here-marker-v2";
const MARKER_SCOPE: &str = "LocalMachine+CurrentUser";
const MARKER_ENTROPY: &[u8] = b"MADAR-keys-here-marker-v2";
const MARKER_HEADER: &str = "madar-keys-here-v2";

/// The data folder's fingerprint (its canonical path, case-insensitive). Pure, tested.
pub fn folder_tag_of(folder: &str) -> String {
    super::hex(&Sha256::digest(
        format!(
            "MADAR-keys-here-folder-v2\n{}",
            folder.trim().to_lowercase()
        )
        .as_bytes(),
    ))
}

/// The current data folder's fingerprint; None if its canonical path cannot be computed (no decision then).
fn folder_tag(data: &Path) -> Option<String> {
    data.canonicalize()
        .ok()
        .map(|f| folder_tag_of(&f.display().to_string()))
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Marker {
    /// Opened by this Windows account on this computer, and it names this folder.
    Valid {
        id: String,
        wanted: bool,
    },
    /// Opened, but it names another folder: positive evidence of a copy of another data folder.
    Foreign,
    Missing,
    /// Present but no decision: it could not be read or opened (another computer or Windows account, a scanner holding it, or an unknown format).
    Unreadable,
}

/// The marker text (pure, tested).
pub fn marker_text(id: &str, tag: &str, wanted: bool) -> String {
    format!(
        "{MARKER_HEADER}\n{id}\n{tag}\n{}",
        if wanted { 1 } else { 0 }
    )
}

/// Reads an opened marker's text (pure, tested). An unknown format = no decision.
pub fn parse_marker(plain: &str, our_tag: Option<&str>) -> Marker {
    let l: Vec<&str> = plain.split('\n').collect();
    let [header, id, tag, wanted] = l[..] else {
        return Marker::Unreadable;
    };
    if header != MARKER_HEADER || !is_hex32(id) || tag.len() != 64 || !matches!(wanted, "0" | "1") {
        return Marker::Unreadable;
    }
    match our_tag {
        None => Marker::Unreadable,
        Some(t) if t == tag => Marker::Valid {
            id: id.to_string(),
            wanted: wanted == "1",
        },
        Some(_) => Marker::Foreign,
    }
}

fn seal_marker(plain: &str) -> Result<Vec<u8>, &'static str> {
    let inner = protect(plain.as_bytes(), MARKER_ENTROPY, false)?;
    let outer = protect(&inner, MARKER_ENTROPY, true)?;
    serde_json::to_vec_pretty(&json!({"format": FORMAT, "purpose": MARKER_PURPOSE, "scope": MARKER_SCOPE, "data": super::hex(&outer)})).map_err(|_| "seal_failed")
}

fn unseal_marker(file: &[u8]) -> Option<Secret> {
    let v: Value = serde_json::from_slice(file).ok()?;
    if v["format"] != FORMAT || v["purpose"] != MARKER_PURPOSE || v["scope"] != MARKER_SCOPE {
        return None;
    }
    let outer = unhex(v["data"].as_str()?)?;
    // The outer seal is LocalMachine (binds to the computer), the inner one CurrentUser (binds to the Windows account).
    let inner = unprotect(&outer, MARKER_ENTROPY).ok()?;
    unprotect(inner.as_bytes(), MARKER_ENTROPY).ok()
}

/// Reads the marker once (no retry).
pub fn check_marker(data: &Path) -> Marker {
    let f = marker_file(data);
    match fs::metadata(&f) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Marker::Missing,
        Err(_) => return Marker::Unreadable,
        Ok(m) if !m.is_file() || m.len() > MAX_SEALED => return Marker::Unreadable,
        Ok(_) => {}
    }
    let Ok(bytes) = fs::read(&f) else {
        return Marker::Unreadable;
    };
    let Some(plain) = unseal_marker(&bytes) else {
        return Marker::Unreadable;
    };
    parse_marker(plain.as_str(), folder_tag(data).as_deref())
}

/// Like `check_marker`, with a short retry when it could not be read (a scanner holding the file for a moment). Only at start and before registration.
fn read_marker(data: &Path) -> Marker {
    let mut m = check_marker(data);
    for attempt in 1..=2u64 {
        if m != Marker::Unreadable {
            break;
        }
        std::thread::sleep(Duration::from_millis(300 * attempt));
        m = check_marker(data);
    }
    m
}

/// Writes the marker (a new ID, or `keep_id` to change only the wish) and checks that it reads back. Returns the ID.
fn make_marker(data: &Path, wanted: bool, keep_id: Option<&str>) -> Result<String, &'static str> {
    fs::create_dir_all(dir(data)).map_err(|_| "save_failed")?;
    let tag = folder_tag(data).ok_or("cannot_verify")?;
    let fresh;
    let id = match keep_id {
        Some(i) if is_hex32(i) => i,
        _ => {
            fresh = Secret::random()?;
            fresh.as_str()
        }
    };
    let sealed = seal_marker(&marker_text(id, &tag, wanted))?;
    write_atomic(&marker_file(data), &sealed)?;
    match check_marker(data) {
        Marker::Valid { id: got, wanted: w } if got == id && w == wanted => Ok(got),
        _ => Err("seal_failed"),
    }
}

/// A file write that is complete or nothing: a temporary file, then a rename, with retries (an antivirus scanner may hold the file for a moment).
fn write_atomic(f: &Path, bytes: &[u8]) -> Result<(), &'static str> {
    let tmp = f.with_extension("tmp");
    for attempt in 0..5 {
        if attempt > 0 {
            std::thread::sleep(Duration::from_millis(200 * attempt));
        }
        let wrote =
            fs::File::create(&tmp).and_then(|mut h| h.write_all(bytes).and_then(|_| h.sync_all()));
        if wrote.is_ok() && fs::rename(&tmp, f).is_ok() {
            return Ok(());
        }
    }
    let _ = fs::remove_file(&tmp);
    Err("save_failed")
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Binding {
    /// The keys belong to this computer, this Windows account and this data folder (the marker is valid).
    Here,
    /// No keys registered from here (no marker, and the state does not expect keys).
    NotHere,
    /// Positive evidence: the marker opened here but names another folder ⇒ a copy. The keys are moved aside and new ones registered.
    Moved,
    /// No decision: the marker cannot be read or opened here, or the state expects keys without a marker. A full node, with no renaming and no deletion.
    Unverified,
}

/// The binding decision (pure, tested) from the marker alone (the account passphrase plays no part: losing it does not stop a running voter), and `keys_expected`
/// (the state says this computer registered keys) to tell "no keys" from "a lost marker".
pub fn binding(m: &Marker, keys_expected: bool) -> Binding {
    match m {
        Marker::Valid { .. } => Binding::Here,
        Marker::Foreign => Binding::Moved,
        Marker::Missing if keys_expected => Binding::Unverified,
        Marker::Missing => Binding::NotHere,
        Marker::Unreadable => Binding::Unverified,
    }
}

/// The node's Keystore folders (`data\node\chains\*\keystore`).
pub fn keystore_dirs(base: &Path) -> Vec<PathBuf> {
    fs::read_dir(base.join("chains"))
        .map(|rd| {
            rd.flatten()
                .map(|e| e.path().join("keystore"))
                .filter(|k| k.is_dir())
                .collect()
        })
        .unwrap_or_default()
}

/// Keystore file names only (4-byte key type + public key, hex): no file is opened and no content is read.
fn keystore_names(base: &Path) -> Vec<String> {
    keystore_dirs(base)
        .iter()
        .flat_map(|d| {
            fs::read_dir(d)
                .map(|rd| {
                    rd.flatten()
                        .filter_map(|e| e.file_name().to_str().map(str::to_lowercase))
                        .collect::<Vec<_>>()
                })
                .unwrap_or_default()
        })
        .collect()
}

/// Every 32-byte public key in a `SessionKeys` encoding has a file named after it in the Keystore (pure, tested; names only).
pub fn keys_match(names: &[String], keys: &[u8]) -> bool {
    !keys.is_empty()
        && keys.len().is_multiple_of(32)
        && keys.chunks(32).all(|k| {
            let want = super::hex(k);
            names.iter().any(|n| {
                n.len() == 72 && n.bytes().all(|c| c.is_ascii_hexdigit()) && n[8..] == want
            })
        })
}

/// A SessionKeys encoding in a single form for comparison (lowercase hex without 0x).
pub fn keys_hex(k: &str) -> String {
    k.trim().trim_start_matches("0x").to_lowercase()
}

/// The result of comparing `NextKeys` on the chain with what is here.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeysCheck {
    /// The registered key files are in this computer's Keystore.
    Match,
    /// Registered again automatically: no keys on the chain, or keys this app sent earlier whose files were lost here.
    ReRegister,
    /// Keys this app never sent: another computer votes with the account. A full node, and the user decides.
    OtherDevice,
}

/// (Pure, tested) `onchain` = `NextKeys` (None/empty = no keys), `names` = the Keystore names, `sent` = what the app sent.
pub fn classify_keys(onchain: Option<&[u8]>, names: &[String], sent: &[String]) -> KeysCheck {
    match onchain {
        None => KeysCheck::ReRegister,
        Some(k) if k.is_empty() => KeysCheck::ReRegister,
        Some(k) if keys_match(names, k) => KeysCheck::Match,
        Some(k) if sent.iter().any(|s| keys_hex(s) == super::hex(k)) => KeysCheck::ReRegister,
        Some(_) => KeysCheck::OtherDevice,
    }
}

/// The maximum number of key sets kept in `last_registered_keys` (newest first).
pub const SENT_KEYS_MAX: usize = 8;

/// Adds a set that was just sent to the front of the list (no duplicates, capped). Pure, tested.
pub fn remember_sent(sent: &mut Vec<String>, keys: &str) {
    let k = keys_hex(keys);
    sent.retain(|s| keys_hex(s) != k);
    sent.insert(0, k);
    sent.truncate(SENT_KEYS_MAX);
}

/// Once it is confirmed that `NextKeys` on the chain are this computer's keys (`KeysCheck::Match`): every Keystore moved aside
/// (`keystore.moved-*`) that names none of the `onchain` keys is wiped, then deleted (no copied secret is kept without need). Returns how many were deleted.
pub fn wipe_stale_aside(base: &Path, onchain: &[u8]) -> usize {
    let want: Vec<String> = onchain.chunks(32).map(super::hex).collect();
    let chains: Vec<PathBuf> = fs::read_dir(base.join("chains"))
        .map(|rd| {
            rd.flatten()
                .map(|e| e.path())
                .filter(|p| p.is_dir())
                .collect()
        })
        .unwrap_or_default();
    let mut n = 0;
    for c in chains {
        let aside: Vec<PathBuf> = fs::read_dir(&c)
            .map(|rd| {
                rd.flatten()
                    .map(|e| e.path())
                    .filter(|p| {
                        p.is_dir()
                            && p.file_name()
                                .and_then(|x| x.to_str())
                                .is_some_and(|x| x.starts_with("keystore.moved-"))
                    })
                    .collect()
            })
            .unwrap_or_default();
        for d in aside {
            let names: Vec<String> = fs::read_dir(&d)
                .map(|rd| {
                    rd.flatten()
                        .filter_map(|e| e.file_name().to_str().map(str::to_lowercase))
                        .collect()
                })
                .unwrap_or_default();
            let names_onchain = names
                .iter()
                .any(|f| f.len() == 72 && f.is_ascii() && want.iter().any(|w| f[8..] == *w));
            if !onchain.is_empty() && !names_onchain && wipe_dir(&d) {
                n += 1;
            }
        }
    }
    n
}

/// Moves the Keystore folders aside **by renaming only** (no reading, no deletion): this computer never signs with copied keys.
/// Returns true only if no Keystore folder is left (all moved aside, or there were none).
fn set_keystore_aside(p: &Paths) -> bool {
    let stamp = now_unix();
    let mut all = true;
    for d in keystore_dirs(&p.base) {
        match fs::rename(&d, aside_path(&d, "moved", stamp)) {
            Ok(()) => log(p, "vote: a keystore folder was set aside (renamed)"),
            Err(e) => {
                all = false;
                log(p, &format!("vote: could not set the keystore aside: {e}"));
            }
        }
    }
    all
}

/// xxHash64 (used in Substrate's `twox` storage keys). Pure, tested against known values.
pub fn xxh64(data: &[u8], seed: u64) -> u64 {
    const P1: u64 = 0x9E37_79B1_85EB_CA87;
    const P2: u64 = 0xC2B2_AE3D_27D4_EB4F;
    const P3: u64 = 0x1656_67B1_9E37_79F9;
    const P4: u64 = 0x85EB_CA77_C2B2_AE63;
    const P5: u64 = 0x27D4_EB2F_1656_67C5;
    let rd64 = |i: usize| u64::from_le_bytes(data[i..i + 8].try_into().unwrap_or([0; 8]));
    let round = |acc: u64, v: u64| {
        acc.wrapping_add(v.wrapping_mul(P2))
            .rotate_left(31)
            .wrapping_mul(P1)
    };
    let merge = |acc: u64, v: u64| (acc ^ round(0, v)).wrapping_mul(P1).wrapping_add(P4);
    let len = data.len();
    let mut i = 0;
    let mut h = if len >= 32 {
        let (mut v1, mut v2, mut v3, mut v4) = (
            seed.wrapping_add(P1).wrapping_add(P2),
            seed.wrapping_add(P2),
            seed,
            seed.wrapping_sub(P1),
        );
        while i + 32 <= len {
            v1 = round(v1, rd64(i));
            v2 = round(v2, rd64(i + 8));
            v3 = round(v3, rd64(i + 16));
            v4 = round(v4, rd64(i + 24));
            i += 32;
        }
        let h = v1
            .rotate_left(1)
            .wrapping_add(v2.rotate_left(7))
            .wrapping_add(v3.rotate_left(12))
            .wrapping_add(v4.rotate_left(18));
        merge(merge(merge(merge(h, v1), v2), v3), v4)
    } else {
        seed.wrapping_add(P5)
    };
    h = h.wrapping_add(len as u64);
    while i + 8 <= len {
        h ^= round(0, rd64(i));
        h = h.rotate_left(27).wrapping_mul(P1).wrapping_add(P4);
        i += 8;
    }
    if i + 4 <= len {
        h ^= (u32::from_le_bytes(data[i..i + 4].try_into().unwrap_or([0; 4])) as u64)
            .wrapping_mul(P1);
        h = h.rotate_left(23).wrapping_mul(P2).wrapping_add(P3);
        i += 4;
    }
    while i < len {
        h ^= (data[i] as u64).wrapping_mul(P5);
        h = h.rotate_left(11).wrapping_mul(P1);
        i += 1;
    }
    h ^= h >> 33;
    h = h.wrapping_mul(P2);
    h ^= h >> 29;
    h = h.wrapping_mul(P3);
    h ^ (h >> 32)
}

pub fn twox128(data: &[u8]) -> [u8; 16] {
    let mut out = [0u8; 16];
    out[..8].copy_from_slice(&xxh64(data, 0).to_le_bytes());
    out[8..].copy_from_slice(&xxh64(data, 1).to_le_bytes());
    out
}

/// The storage key of `Session.NextKeys(account)` (Twox64Concat). Pure, tested.
pub fn next_keys_storage_key(account: &[u8]) -> String {
    let mut k = Vec::with_capacity(32 + 8 + account.len());
    k.extend_from_slice(&twox128(b"Session"));
    k.extend_from_slice(&twox128(b"NextKeys"));
    k.extend_from_slice(&xxh64(account, 0).to_le_bytes());
    k.extend_from_slice(account);
    format!("0x{}", super::hex(&k))
}

/// The public keys registered on the chain for the operator account (safe RPC: `state_getStorage`). None = the question failed;
/// Some(None) = no keys stored.
fn next_keys(port: u16, account_hex: &str) -> Option<Option<Vec<u8>>> {
    let acc = unhex(account_hex)?;
    let v = rpc(
        port,
        "state_getStorage",
        json!([next_keys_storage_key(&acc)]),
    )?;
    if v.is_null() {
        return Some(None);
    }
    Some(Some(unhex(v.as_str()?.trim_start_matches("0x"))?))
}

