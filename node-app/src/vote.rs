//! "Enable voting" (2.0.14): turns the regular node into a voting node for an approved operator, with no manual commands
//! (internal design note).
//!
//! - The app **only coordinates**: every chain step is a `madar-node join …` command run as a child process with explicit arguments. No chain logic here,
//!   and no PowerShell, cmd or scripts. The app itself never reads Keystore files (only their names), and reads `data\node-key` once
//!   at start to derive the node's **public** ID from it (to check that the RPC is our node); the key is never logged or shown.
//! - The operator account: `join new-account` writes it encrypted (Argon2id) to `data\vote\operator.enc` with the public `operator.pub`.
//!   Its passphrase is random (32 bytes), generated by the app and sealed at once with DPAPI (CurrentUser) in `operator.pass.sealed.json`.
//!   The passphrase is never shown, never written in plain form to disk, and never passes through a command line, an environment variable, a log or an error message: it is handed
//!   to the child command through a one-time named pipe (`--passphrase-file \\.\pipe\…`) that only this Windows account can open, then wiped.
//! - **Never any unsafe RPC** (review 2026-10-17, round 3): the session keys are generated with `join gen-keys` while the node is **stopped**,
//!   directly in the node's Keystore (it prints only the public keys), then the node comes back as a voter with safe RPC, and `join register-keys --keys` produces the
//!   ownership proof locally from the Keystore files and sends `set_keys` over the safe RPC. No `--rpc-methods unsafe` in any mode.
//! - One voting node per operator: if the account has registered keys that this computer did not register, the app refuses to continue.
//! - "The keys are here" is decided **by the sealed marker alone** (`keys-here.sealed.json`): a double DPAPI seal (inner CurrentUser,
//!   outer LocalMachine) holding a random ID, the data folder's fingerprint and the wish (`wanted`). It opens here and matches the folder ⇒ here. It opens
//!   but the folder fingerprint does not match (positive evidence of a copy) ⇒ the Keystore is moved aside **by renaming only** and new keys are registered.
//!   Any failure to open or read it ⇒ a full node and the "could not verify" phase, with no renaming or deletion at all (the user decides).
//! - DPAPI is opened at start and right before a command that needs the secret only (not every round), and the TCP port table is read before sending commands only.

