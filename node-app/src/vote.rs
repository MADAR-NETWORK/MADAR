    #[test]
    fn old_temporary_files_and_stale_aside_keystores_are_wiped() {
        let root = temp_root("wipe");
        let p = paths_at(&root);
        fs::create_dir_all(dir(&p.data)).unwrap();
        let old = dir(&p.data).join("export-0011.tmp");
        let new = dir(&p.data).join("import-2233.tmp");
        let other = dir(&p.data).join("state.json");
        for f in [&old, &new, &other] {
            fs::write(f, b"{\"wanted\":true}").unwrap();
        }
        let hours_ago = std::time::SystemTime::now() - Duration::from_secs(2 * TMP_MAX_AGE);
        fs::File::options()
            .write(true)
            .open(&old)
            .unwrap()
            .set_modified(hours_ago)
            .unwrap();
        fs::File::options()
            .write(true)
            .open(&other)
            .unwrap()
            .set_modified(hours_ago)
            .unwrap();
        assert_eq!(clean_old_tmp(&p.data), 1);
        assert!(
            !old.exists() && new.exists() && other.exists(),
            "only .tmp files older than an hour"
        );
        // aside keystores: wiped only when the chain does not name any of their keys
        let chain_dir = p.base.join("chains").join("madar");
        let live = chain_dir.join("keystore");
        let stale = chain_dir.join("keystore.moved-1");
        let named = chain_dir.join("keystore.moved-2");
        for (d, k) in [(&live, "bb"), (&stale, "aa"), (&named, "cc")] {
            fs::create_dir_all(d).unwrap();
            fs::write(d.join(format!("6772616e{}", k.repeat(32))), b"\"seed\"").unwrap();
        }
        let onchain: Vec<u8> = [[0xbbu8; 32], [0xccu8; 32]].concat();
        assert_eq!(
            wipe_stale_aside(&p.base, &[]),
            0,
            "nothing confirmed: nothing deleted"
        );
        assert_eq!(wipe_stale_aside(&p.base, &onchain), 1);
        assert!(!stale.exists() && named.exists() && live.exists());
        let _ = fs::remove_dir_all(&root);
    }

