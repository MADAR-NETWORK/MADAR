fn set_view(state: &Arc<Mutex<State>>, f: impl FnOnce(&mut Value)) {
    let mut st = state.lock().unwrap();
    f(&mut st.vote);
}

/// Changes the node mode and restarts the node with it. A voter is refused if the node cannot be tied to the app's job object: it stays a full node.
fn set_mode(p: &Paths, state: &Arc<Mutex<State>>, mode: NodeMode) {
    let mut st = state.lock().unwrap();
    let mode = if st.job_failed { NodeMode::Full } else { mode };
    if st.node_mode == mode {
        return;
    }
    log(
        p,
        &format!("vote: node mode {:?} -> {mode:?}", st.node_mode),
    );
    st.node_mode = mode;
    if let Err(e) = update_local(&p.data, |l| l.validator = mode == NodeMode::Validator) {
        log(p, &format!("vote: saving state failed: {e}"));
    }
    if st.child.is_some() && !st.stopping && st.paused.is_none() {
        stop_node(p, &mut st);
        st.crashes.clear();
        start_node(p, &mut st);
    }
}

/// The node runs and is in sync (decisions on an old state could resend a transaction).
fn node_ready(state: &Arc<Mutex<State>>) -> Option<u16> {
    let port = {
        let mut st = state.lock().unwrap();
        if st.stopping
            || st.paused.is_some()
            || st.bootstrap.is_some()
            || st.needs_repair
            || !super::node_alive(&mut st)
        {
            return None;
        }
        super::rpc_port(&st)
    };
    let h = rpc(port, "system_health", json!([]))?;
    (h["isSyncing"].as_bool() == Some(false) && h["peers"].as_u64().unwrap_or(0) > 0)
        .then_some(port)
}

fn wait_ready(state: &Arc<Mutex<State>>, max: Duration) -> Option<u16> {
    let deadline = Instant::now() + max;
    loop {
        if let Some(port) = node_ready(state) {
            return Some(port);
        }
        if Instant::now() > deadline {
            return None;
        }
        std::thread::sleep(Duration::from_secs(5));
    }
}

/// Our port is owned by another process: a new port and a node restart with it, up to `MAX_REPICKS` times in one run.
fn repick_rpc_port(p: &Paths, state: &Arc<Mutex<State>>, cache: &mut Cache) -> bool {
    if cache.repicks >= MAX_REPICKS {
        return false;
    }
    cache.repicks += 1;
    let mut st = state.lock().unwrap();
    let (ui, rpc_now, prom, p2p) = st.ports;
    let Some(port) = next_rpc_port(rpc_now, &[ui, rpc_now, prom, p2p], |x| {
        std::net::TcpListener::bind(("127.0.0.1", x)).is_ok()
    }) else {
        return false;
    };
    log(p, &format!("vote: RPC port {rpc_now} is held by another program; the node moves to port {port} (try {})", cache.repicks));
    st.ports.1 = port;
    let _ = fs::write(
        &p.ports,
        json!({"ui": ui, "rpc": port, "prom": prom, "p2p": p2p}).to_string(),
    );
    if !st.stopping && st.paused.is_none() {
        stop_node(p, &mut st);
        st.crashes.clear();
        start_node(p, &mut st);
    }
    true
}

/// Creates the sealed passphrase file **new only** and checks that it opens. Never touches an existing file.
fn write_new_sealed(data: &Path, secret: &Secret) -> Result<(), Failure> {
    let sealed = seal(secret).map_err(fail)?;
    fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(sealed_file(data))
        .and_then(|mut f| f.write_all(&sealed).and_then(|_| f.sync_all()))
        .map_err(|_| fail("save_failed"))?;
    match load_secret(data) {
        Ok(back) if back.as_bytes() == secret.as_bytes() => Ok(()),
        _ => {
            // We created the file in this very call and it protects nothing yet.
            let _ = fs::remove_file(sealed_file(data));
            Err(fail("seal_failed"))
        }
    }
}

/// Creates the account: the passphrase is sealed and written first (then checked to open), and only after that `join new-account`. Refuses if **any** account file exists
/// (an existing passphrase or public file is never deleted).
fn create_account(p: &Paths) -> Result<(), Failure> {
    let _g = ACCOUNT_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let _ = fs::create_dir_all(dir(&p.data));
    if any_account_file(&p.data) {
        return Err(fail("account_broken"));
    }
    let secret = Secret::random().map_err(fail)?;
    write_new_sealed(&p.data, &secret)?;
    let r = run_join(p, None, None, &Join::NewAccount, 0, Some(&secret), None);
    if r.is_err() || !has_account(&p.data) {
        // Undo only what this call created, and only if the account file was not written (the passphrase protects it if it was).
        if !enc_file(&p.data).exists() && !pub_file(&p.data).exists() {
            let _ = fs::remove_file(sealed_file(&p.data));
        }
        return Err(r.err().unwrap_or_else(|| fail("command_failed")));
    }
    Ok(())
}

/// "Recreate the operator account": the broken account's files are moved aside by renaming (no deletion: it may be restored on its original computer),
/// along with the keys marker; a new account is then created in the next round.
fn set_account_aside(p: &Paths) -> Result<(), Failure> {
    let stamp = now_unix();
    let enc = enc_file(&p.data);
    for f in [
        enc.clone(),
        pub_file(&p.data),
        sealed_file(&p.data),
        enc.with_extension("rotation.json"),
        marker_file(&p.data),
    ] {
        if f.exists() {
            fs::rename(&f, aside_path(&f, "broken", stamp)).map_err(|e| Failure {
                code: "save_failed",
                detail: e.to_string(),
            })?;
        }
    }
    update_local(&p.data, |l| {
        l.recreate = false;
        l.keys_expected = false;
        l.rekey = false;
        l.validator = false;
        l.account_hex = None;
        l.pending_keys = None;
        l.keys_mismatch = false;
        l.keys_foreign = false;
        l.sent_keys.clear();
        l.last_phase = None;
        l.fail_step = None;
        l.fail_count = 0;
        l.retry_at = None;
    })
    .map_err(fail)
}

/// The keys step with no unsafe RPC at all:
/// 1) the "keys are here" marker for this folder; 2) unless pending keys with existing files are present: stop the node → `join gen-keys` → start it
///    as a voter (safe RPC); 3) wait for the node; 4) check both file names in the Keystore; 5) `keys_expected` before sending;
/// 6) `join register-keys --keys` (local ownership proof).
fn register_keys(
    p: &Paths,
    state: &Arc<Mutex<State>>,
    cache: &mut Cache,
    l: &Local,
) -> Result<(), Failure> {
    if state.lock().unwrap().job_failed {
        return Err(fail("job_failed"));
    }
    match read_marker(&p.data) {
        Marker::Valid { .. } => {}
        Marker::Missing => {
            make_marker(&p.data, l.wanted, None).map_err(fail)?;
        }
        // Never write over a marker that cannot be read (no decision then).
        _ => return Err(fail("cannot_verify")),
    }
    cache.binding = Binding::Here;
    cache.marker_wanted = Some(l.wanted);
    let names = keystore_names(&p.base);
    let reuse = l
        .pending_keys
        .as_deref()
        .and_then(|k| unhex(k.trim_start_matches("0x")))
        .filter(|k| k.len() == 64 && keys_match(&names, k));
    let keys = match reuse {
        Some(_) => l.pending_keys.clone().unwrap_or_default(),
        None => {
            {
                let mut st = state.lock().unwrap();
                if st.stopping || st.paused.is_some() {
                    return Err(fail("node_not_ready"));
                }
                // The node is stopped during the whole generation, and the lock is **not** held during the slow steps (the page and the monitor keep working): `keys_busy`
                // keeps the monitor from restarting it meanwhile. It comes back as a voter only if the generation succeeded.
                st.keys_busy = true;
                stop_node(p, &mut st);
            }
            let out = run_join(p, None, None, &Join::GenKeys, 0, None, None);
            {
                let mut st = state.lock().unwrap();
                if out.is_ok() {
                    st.node_mode = NodeMode::Validator;
                }
                st.keys_busy = false;
                st.crashes.clear();
                if !st.stopping && st.paused.is_none() {
                    start_node(p, &mut st);
                }
            }
            let out = out?;
            if let Err(e) = update_local(&p.data, |x| x.validator = true) {
                log(p, &format!("vote: saving state failed: {e}"));
            }
            let (keys, _) = parse_gen_keys(&out).map_err(fail)?;
            update_local(&p.data, |x| x.pending_keys = Some(keys.clone())).map_err(fail)?;
            log(p, "vote: new session keys were generated in the node keystore (node stopped meanwhile)");
            keys
        }
    };
    set_mode(p, state, NodeMode::Validator);
    let port = wait_ready(state, Duration::from_secs(KEYS_NODE_WAIT))
        .ok_or_else(|| fail("node_not_ready"))?;
    // Names only: both files are in the Keystore before sending.
    let bytes = unhex(keys.trim_start_matches("0x")).unwrap_or_default();
    if !keys_match(&keystore_names(&p.base), &bytes) {
        let _ = update_local(&p.data, |x| x.pending_keys = None);
        return Err(fail("keys_missing"));
    }
    // (3) The last check right before sending: the node really is a voter and tied to the app's job object (no keys for a node that cannot vote).
    {
        let st = state.lock().unwrap();
        if !may_send_keys(st.job_failed, st.node_mode) {
            return Err(fail("job_failed"));
        }
    }
    // Before sending: any keys that appear for this account after this were registered by this computer (no wrong "another computer" refusal if the command is cut after sending),
    // and the set is saved in `last_registered_keys` (telling "our keys lost their files" from "another computer").
    update_local(&p.data, |x| {
        x.keys_expected = true;
        remember_sent(&mut x.sent_keys, &keys);
    })
    .map_err(fail)?;
    run_join(
        p,
        Some(state),
        cache.peer.as_deref(),
        &Join::RegisterKeys(keys),
        port,
        None,
        None,
    )?;
    if let Err(e) = update_local(&p.data, |x| {
        x.rekey = false;
        x.keys_mismatch = false;
        x.keys_foreign = false;
        x.keys_checked = Some(checked_after_register(now_unix()));
    }) {
        log(p, &format!("vote: saving state failed: {e}"));
    }
    Ok(())
}

/// Saves a change from the round; a failure shows on the card and is logged.
fn save_or_report(p: &Paths, state: &Arc<Mutex<State>>, f: impl FnOnce(&mut Local)) -> bool {
    match update_local(&p.data, f) {
        Ok(()) => true,
        Err(e) => {
            log(p, &format!("vote: saving state failed: {e}"));
            set_view(state, |v| v["error"] = json!(e));
            false
        }
    }
}

/// How long to wait until the next round if the step is postponed after a failure.
fn wait_for(l: &Local, step: Step, now: u64) -> u64 {
    match l.retry_at {
        Some(r) if l.fail_step.as_deref() == Some(step_key(step).as_str()) && r > now => {
            (r - now).clamp(60, 1800)
        }
        _ => poll_secs(step),
    }
}

/// How often `NextKeys` is compared with the Keystore names once they matched (seconds).
pub const KEYS_RECHECK: u64 = 6 * 3600;

/// The first comparison after a registration waits this long (seconds) for the transaction to show on the chain: no "another computer" verdict on old keys.
pub const KEYS_SETTLE: u64 = 180;

/// The `keys_checked` value after a successful registration: the next comparison is due after `KEYS_SETTLE` (pure, tested).
pub fn checked_after_register(now: u64) -> u64 {
    now.saturating_sub(KEYS_RECHECK - KEYS_SETTLE)
}

/// Compare now? (pure, tested): the first time, after each registration by `KEYS_SETTLE`, then every `KEYS_RECHECK`.
pub fn keys_check_due(l: &Local, now: u64) -> bool {
    // "Another computer" is checked again every 10 minutes: this computer's set that arrived late reaches "match" and clears the flag by itself.
    let every = if l.keys_foreign {
        KEYS_FOREIGN_RECHECK
    } else {
        KEYS_RECHECK
    };
    l.keys_here && l.keys_checked.is_none_or(|t| t > now || now - t >= every)
}

/// Re-check of "another computer" (seconds).
pub const KEYS_FOREIGN_RECHECK: u64 = 600;

/// For this long (seconds) after this computer registered its keys there is no "another computer" verdict: the transaction may be slow to reach the chain.
pub const KEYS_GRACE: u64 = 1800;

/// The verdict after the registration grace (pure, tested): `OtherDevice` within the first `KEYS_GRACE` after our registration = wait (None).
pub fn settle_verdict(v: KeysCheck, last_keys: Option<u64>, now: u64) -> Option<KeysCheck> {
    match (v, last_keys) {
        (KeysCheck::OtherDevice, Some(t)) if t <= now && now - t < KEYS_GRACE => None,
        _ => Some(v),
    }
}

/// The chain state of the operator account. For a broken account: by the saved address, or by decrypting `.enc` if `.pub` is missing and the passphrase opens; the decryption is tried
/// once per run (its failure is kept in `cache`, no DPAPI in every round). Returns (the status, `unknowable`).
fn chain_status(
    p: &Paths,
    state: &Arc<Mutex<State>>,
    cache: &mut Cache,
    l: &Local,
    port: u16,
) -> (Result<Chain, Failure>, bool) {
    let parse = |r: Result<String, Failure>| r.and_then(|out| parse_status(&out).map_err(fail));
    if !l.broken {
        return (
            parse(run_join(
                p,
                Some(state),
                cache.peer.as_deref(),
                &Join::Status,
                port,
                None,
                None,
            )),
            false,
        );
    }
    if let Some(h) = account_id_hex(&p.data).or_else(|| l.account_hex.clone()) {
        return (
            parse(run_join(
                p,
                Some(state),
                cache.peer.as_deref(),
                &Join::StatusOf(h),
                port,
                None,
                None,
            )),
            false,
        );
    }
    if enc_file(&p.data).exists() && !cache.enc_status_failed {
        match load_secret(&p.data) {
            Ok(s) => {
                return (
                    parse(run_join(
                        p,
                        Some(state),
                        cache.peer.as_deref(),
                        &Join::Status,
                        port,
                        Some(&s),
                        None,
                    )),
                    false,
                )
            }
            Err(e) => {
                log(p, &format!("vote: the broken account's passphrase cannot be opened ({e}); not tried again in this run"));
                cache.enc_status_failed = true;
            }
        }
    }
    // No address and no passphrase: the account can never be known or used.
    let unknowable = !sealed_file(&p.data).exists() || cache.secret_ok == Some(false);
    (Err(fail("account_unknown")), unknowable)
}

fn tick(p: &Paths, state: &Arc<Mutex<State>>, cache: &mut Cache) -> u64 {
    let now = now_unix();
    let mut l = match load_local(&p.data) {
        Ok(l) => l,
        Err(e) => {
            // No decision and no write on a state that cannot be read now.
            log(p, &format!("vote: {e}; this check is skipped"));
            set_view(state, |v| v["error"] = json!(e));
            return 120;
        }
    };
    if cache.peer.is_none() {
        cache.peer = super::rewards::load_key(&p.data).map(|k| super::rewards::peer_id(&k));
    }
    // The state was lost but the valid marker carries the wish: it comes back (and the keys are here by the marker).
    if l.state_lost && cache.binding == Binding::Here {
        if let Some(w) = cache.marker_wanted {
            if save_or_report(p, state, |x| {
                x.state_lost = false;
                x.wanted = w;
                x.keys_expected = true;
            }) {
                log(
                    p,
                    "vote: the lost voting state was restored from the sealed marker",
                );
                l.state_lost = false;
                l.wanted = w;
                l.keys_expected = true;
            }
        }
    }
    // (4) The marker could not be read: it is read again with a delay (5, then every 10 minutes); valid ⇒ the keys are here and the node is a voter again.
    match recheck_marker(&p.data, cache, l.keys_expected, Instant::now()) {
        Some(Binding::Here) => {
            log(
                p,
                "vote: the sealed marker can be read again; the voting keys are here",
            );
            if !l.keys_foreign
                && (l.validator || l.wanted || (l.state_lost && cache.marker_wanted == Some(true)))
            {
                set_mode(p, state, NodeMode::Validator);
            }
        }
        Some(Binding::Moved) => {
            if set_keys_aside(
                p,
                Some(state),
                cache.secret_ok == Some(true),
                "the voting keys belong to another data folder",
            ) {
                cache.binding = Binding::NotHere;
                if let Ok(x) = load_local(&p.data) {
                    l = x;
                }
            } else {
                cache.binding = Binding::Unverified;
                cache.marker_recheck = true;
                cache.marker_next = Some(Instant::now() + Duration::from_secs(MARKER_RETRY));
            }
        }
        _ => {}
    }
    // The "Register new keys for this computer" button (the user decided): no binding decision ⇒ renaming only; another computer's keys on the chain
    // ⇒ this computer takes over the account with new keys (`rekey`).
    let rekey_asked = std::mem::take(&mut state.lock().unwrap().vote_rekey);
    if rekey_asked
        && cache.binding == Binding::Unverified
        && set_keys_aside(
            p,
            Some(state),
            cache.secret_ok == Some(true),
            "the user chose new voting keys for this computer",
        )
    {
        cache.binding = Binding::NotHere;
        cache.marker_wanted = None;
        if let Ok(x) = load_local(&p.data) {
            l = x;
        }
    } else if rekey_asked && cache.binding == Binding::Here && l.keys_foreign {
        let take_over = |x: &mut Local| {
            x.keys_foreign = false;
            x.keys_mismatch = false;
            x.pending_keys = None;
            x.rekey = true;
        };
        if save_or_report(p, state, take_over) {
            log(p, "vote: the user chose new voting keys for this computer (the chain named keys of another computer)");
            take_over(&mut l);
        }
    }
    l.keys_here = cache.binding == Binding::Here;
    l.unverified = cache.binding == Binding::Unverified;
    l.broken = l.broken || (l.account && cache.secret_ok == Some(false));
    if l.account && l.account_hex.is_none() {
        if let Some(h) = account_id_hex(&p.data) {
            if save_or_report(p, state, |x| x.account_hex = Some(h.clone())) {
                l.account_hex = Some(h);
            }
        }
    }
    set_view(state, |v| {
        v["wanted"] = json!(l.wanted);
        v["address"] = json!(address(&p.data));
        v["can_recreate"] = json!(false);
        v["has_account_files"] = json!(any_account_file(&p.data));
    });
    if l.state_lost {
        set_view(state, |v| v["stage"] = json!("state_lost"));
        return poll_secs(Step::StateLost);
    }
    if !l.account && !l.broken && !l.wanted {
        set_view(state, |v| v["stage"] = json!("off"));
        return 3600;
    }
    if !l.account && !l.broken {
        let step = Step::CreateAccount;
        set_view(state, |v| {
            v["stage"] = json!(if is_stuck(&l, step) {
                "stuck"
            } else {
                "creating"
            })
        });
        if !should_run(step, &l, now) {
            return wait_for(&l, step, now);
        }
        set_view(state, |v| v["busy"] = json!(true));
        let r = create_account(p);
        save_or_report(p, state, |x| note_attempt(x, step, now));
        if r.is_ok() {
            cache.secret_ok = Some(true);
        }
        set_view(state, |v| {
            v["busy"] = json!(false);
            v["error"] = json!(r.as_ref().err().map(|f| f.code));
            v["address"] = json!(address(&p.data));
        });
        match r {
            Ok(()) => log(p, "vote: operator account created"),
            Err(f) => log(
                p,
                &format!("vote: create account failed: {} {}", f.code, f.detail),
            ),
        }
        return 30;
    }
    let Some(port) = node_ready(state) else {
        set_view(state, |v| {
            v["stage"] = json!(if l.wanted { "node_not_ready" } else { "off" })
        });
        return 60;
    };
    let (status, unknowable) = chain_status(p, state, cache, &l, port);
    let chain = match status {
        Ok(c) => Some(c),
        Err(f) => {
            log(p, &format!("vote: status failed: {} {}", f.code, f.detail));
            if f.code == "rpc_not_ours" && repick_rpc_port(p, state, cache) {
                set_view(state, |v| v["stage"] = json!("node_not_ready"));
                return 30;
            }
            set_view(state, |v| {
                v["error"] = json!(f.code);
                if f.code == "rpc_not_ours" {
                    v["stage"] = json!("rpc_not_ours");
                }
            });
            None
        }
    };
    if let Some(c) = &chain {
        cache.repicks = 0;
        let phase = phase_name(c.phase).to_string();
        if l.last_phase.as_deref() != Some(phase.as_str())
            && save_or_report(p, state, |x| x.last_phase = Some(phase.clone()))
        {
            l.last_phase = Some(phase);
        }
        // After registration (then every 6 hours): does `NextKeys` on the chain have files named after it in the Keystore? (names only). If not: automatic
        // registration only if there are no keys, or the set was sent by this app itself and its files were lost; a set it never sent = another computer.
        if c.keys_registered && keys_check_due(&l, now) {
            if let Some(onchain) = l.account_hex.clone().and_then(|a| next_keys(port, &a)) {
                let raw = classify_keys(onchain.as_deref(), &keystore_names(&p.base), &l.sent_keys);
                // Our registration is recent and has not arrived yet: no "another computer" verdict; a new check after `KEYS_SETTLE`.
                if let Some(verdict) = settle_verdict(raw, l.last_keys, now) {
                    match verdict {
                        KeysCheck::Match => {},
                        KeysCheck::ReRegister => log(p, "vote: the voting keys on the chain are this app's own (or none) but their files are not in this node's keystore; they will be registered again"),
                        KeysCheck::OtherDevice => log(p, "vote: the chain names voting keys this app never registered (another computer votes with this account); this node stays a full node until the user decides"),
                    }
                    let apply = |x: &mut Local| {
                        x.keys_checked = Some(now);
                        x.keys_mismatch = verdict == KeysCheck::ReRegister;
                        x.keys_foreign = verdict == KeysCheck::OtherDevice;
                        if verdict == KeysCheck::Match {
                            x.pending_keys = None;
                        }
                    };
                    if save_or_report(p, state, apply) {
                        apply(&mut l);
                    }
                    // (9) This computer's keys are confirmed on the chain: a Keystore moved aside that `NextKeys` does not name is wiped, then deleted.
                    if let (KeysCheck::Match, Some(k)) = (verdict, onchain.as_deref()) {
                        let n = wipe_stale_aside(&p.base, k);
                        if n > 0 {
                            log(p, &format!("vote: {n} set-aside keystore folder(s) no longer named on the chain were wiped"));
                        }
                    }
                } else {
                    let again = checked_after_register(now);
                    if save_or_report(p, state, |x| x.keys_checked = Some(again)) {
                        l.keys_checked = Some(again);
                    }
                }
            }
        }
        // No keys on the chain now: no "another computer" from now on (this computer's keys will be registered).
        if !c.keys_registered
            && l.keys_foreign
            && save_or_report(p, state, |x| x.keys_foreign = false)
        {
            l.keys_foreign = false;
        }
    }
    let current = state.lock().unwrap().node_mode;
    set_mode(p, state, node_mode(&l, chain.as_ref(), current));
    let step = decide(&l, chain.as_ref(), unknowable);
    let job_failed = state.lock().unwrap().job_failed;
    set_view(state, |v| {
        v["can_recreate"] = json!(recreate_allowed(l.broken, chain.as_ref(), unknowable));
        if job_failed {
            v["error"] = json!("job_failed");
        }
    });
    let Some(c) = chain else {
        if matches!(step, Step::AccountBroken | Step::RecreateAccount) {
            set_view(state, |v| v["stage"] = json!("account_broken"));
        }
        if step != Step::RecreateAccount {
            return 120;
        }
        // An account that cannot be known and the user asked to recreate it: it is moved aside.
        let r = set_account_aside(p);
        log(
            p,
            &format!(
                "vote: unusable account set aside: {}",
                r.as_ref()
                    .map(|_| "ok".to_string())
                    .unwrap_or_else(|f| f.code.to_string())
            ),
        );
        return 10;
    };
    if note_progress(&mut l, step) {
        save_or_report(p, state, |x| {
            note_progress(x, step);
        });
    }
    if l.recreate && !l.broken {
        save_or_report(p, state, |x| x.recreate = false);
    }
    set_view(state, |v| {
        v["stage"] = json!(if is_stuck(&l, step) {
            "stuck"
        } else {
            stage(step)
        });
        v["current_session"] = json!(c.current_session);
        v["expiry_session"] = json!(c.expiry);
        v["checked_unix"] = json!(now_unix());
        v["error"] = if job_failed {
            json!("job_failed")
        } else if l.keys_mismatch && l.keys_here {
            json!("keys_mismatch")
        } else {
            Value::Null
        };
    });
    if !should_run(step, &l, now) {
        return wait_for(&l, step, now);
    }
    // (3) The node cannot be a voter in this run (no job object): no applying, no renewal and no keys (exit is allowed).
    if blocked_by_job(step, job_failed) {
        log(
            p,
            &format!(
                "vote: {} skipped: the node cannot be a voting node in this run (job object)",
                step_key(step)
            ),
        );
        return 1800;
    }
    // The step's last time is saved before sending; if saving fails we do not send (no double send after a restart).
    let stamped = match step {
        Step::Vouch => save_or_report(p, state, |x| x.last_vouch = Some(now)),
        Step::Apply => save_or_report(p, state, |x| x.last_apply = Some(now)),
        Step::RegisterKeys => save_or_report(p, state, |x| x.last_keys = Some(now)),
        Step::Renew => save_or_report(p, state, |x| x.last_renew = Some(now)),
        Step::Exit => save_or_report(p, state, |x| x.last_exit = Some(now)),
        _ => true,
    };
    if !stamped {
        return 300;
    }
    set_view(state, |v| v["busy"] = json!(true));
    let peer = cache.peer.clone();
    let r = match step {
        Step::Vouch => run_join(
            p,
            Some(state),
            peer.as_deref(),
            &Join::Vouch,
            port,
            None,
            None,
        )
        .map(|_| ()),
        Step::Apply => run_join(
            p,
            Some(state),
            peer.as_deref(),
            &Join::Apply,
            port,
            None,
            None,
        )
        .map(|_| ()),
        Step::RegisterKeys => register_keys(p, state, cache, &l),
        Step::Renew => run_join(
            p,
            Some(state),
            peer.as_deref(),
            &Join::AutoRenew,
            port,
            None,
            None,
        )
        .map(|_| ()),
        Step::Exit => run_join(
            p,
            Some(state),
            peer.as_deref(),
            &Join::Exit,
            port,
            None,
            None,
        )
        .map(|_| ()),
        Step::RecreateAccount => set_account_aside(p),
        _ => Ok(()),
    };
    if matches!(&r, Err(f) if f.code == "unseal_failed") {
        cache.secret_ok = Some(false);
    }
    // Cancelled because the node stopped: not a failure of the step.
    if !matches!(&r, Err(f) if f.code == "cancelled") && step != Step::RecreateAccount {
        save_or_report(p, state, |x| note_attempt(x, step, now));
    }
    let repicked =
        matches!(&r, Err(f) if f.code == "rpc_not_ours") && repick_rpc_port(p, state, cache);
    set_view(state, |v| {
        v["busy"] = json!(false);
        v["error"] = json!(r.as_ref().err().map(|f| f.code));
        if matches!(&r, Err(f) if f.code == "rpc_not_ours") && !repicked {
            v["stage"] = json!("rpc_not_ours");
        }
    });
    match r {
        Ok(()) => log(p, &format!("vote: {} done", step_key(step))),
        Err(f) => log(
            p,
            &format!("vote: {} failed: {} {}", step_key(step), f.code, f.detail),
        ),
    }
    if step == Step::RecreateAccount {
        return 10;
    }
    poll_secs(step)
}

/// The voting thread: asks the chain when needed, or at once after a button press (`vote_kick`).
pub fn spawn(state: Arc<Mutex<State>>, mut cache: Cache) {
    std::thread::spawn(move || {
        let p = super::paths();
        let mut next = Instant::now() + Duration::from_secs(45);
        loop {
            std::thread::sleep(Duration::from_secs(5));
            let kicked = std::mem::take(&mut state.lock().unwrap().vote_kick);
            if !kicked && Instant::now() < next {
                continue;
            }
            let wait = tick(&p, &state, &mut cache);
            next = Instant::now() + Duration::from_secs(wait);
        }
    });
}

