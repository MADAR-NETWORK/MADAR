#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Phase {
    Banned,
    NotStarted,
    Candidate,
    KeysOnly,
    Member,
    MemberInGrace,
    Exiting,
}

/// What we read from `join status --json`.
#[derive(Debug, Clone, PartialEq)]
pub struct Chain {
    pub phase: Phase,
    pub current_session: u32,
    pub expiry: Option<u32>,
    pub renewable: bool,
    pub keys_registered: bool,
    pub keys_held_by_node: Option<bool>,
    pub active: bool,
    /// `ApprovedOperators`: `None` if `madar-node` did not report it (a version older than "Enable voting").
    pub approved: Option<bool>,
    /// `NodeOperator`: the same.
    pub vouched: Option<bool>,
}

pub fn parse_status(out: &str) -> Result<Chain, &'static str> {
    let v: Value = serde_json::from_str(out.trim()).map_err(|_| "status_unreadable")?;
    let s = &v["status"];
    let phase = match s["phase"].as_str().ok_or("status_unreadable")? {
        "banned" => Phase::Banned,
        "not_started" => Phase::NotStarted,
        "candidate" => Phase::Candidate,
        "keys_only" => Phase::KeysOnly,
        "member" => Phase::Member,
        "member_in_grace" => Phase::MemberInGrace,
        "exiting" => Phase::Exiting,
        _ => return Err("status_unreadable"),
    };
    Ok(Chain {
        phase,
        current_session: s["current_session"].as_u64().ok_or("status_unreadable")? as u32,
        expiry: s["expiry_session"].as_u64().map(|x| x as u32),
        renewable: s["renewable"].as_bool().unwrap_or(false),
        keys_registered: s["keys_registered"].as_bool().unwrap_or(false),
        keys_held_by_node: s["keys_held_by_node"].as_bool(),
        active: s["active_authority"].as_bool().unwrap_or(false),
        approved: v["operator_approved"].as_bool(),
        vouched: v["vouched"].as_bool(),
    })
}

